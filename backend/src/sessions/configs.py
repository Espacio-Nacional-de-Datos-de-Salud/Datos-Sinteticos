"""Config-file discovery and editing service.

Walks ``backend/config/`` to return config files (YAML, Python, JSON, TOML)
grouped by logical scope (pipeline / evaluation / rules / all), and
resolves/reads/writes the real ``*.yaml`` file for each committed
``*.example.yaml`` template.

Important distinction from ``backend.src.config``:
- This module manages config *files on disk* (discovery, path resolution,
    read/write/reset).
- ``backend.src.config`` modules expose config *runtime values* consumed by
    Python code.

Layout:
- Committed templates are ``backend/config/<name>.example.yaml`` (and
    equivalents under ``pipelines/``).
- The real, user-editable ``<name>.yaml`` file sits next to the template and
    is gitignored. ``make config`` bootstraps it by copying the template.
- The frontend / API edits the real ``*.yaml`` only; ``*.example.yaml``
    files are read-only references.
"""

import json
from pathlib import Path

import yaml
from backend.src.api.schemas.configs import ConfigFile, ConfigScope
from backend.src.config.general import CONFIG_DIR

_CONFIG_ROOT = Path(CONFIG_DIR)
_PROJECT_ROOT = Path(__file__).resolve().parents[3]
_FRONTEND_ENV_EXAMPLE = _PROJECT_ROOT / "frontend" / "env.example.local"
_FRONTEND_ENV_LOCAL = _PROJECT_ROOT / "frontend" / ".env.local"

_EXAMPLE_SUFFIX = ".example"  # file stem suffix, e.g. "general.example.yaml"
_CONFIG_SUFFIXES = {".yaml", ".yml", ".py", ".json", ".toml"}

_EXAMPLE_CONFIG_HEADER_MARK = "TEMPLATE — DO NOT EDIT THIS FILE."
_REAL_CONFIG_HEADER = (
    "# ─────────────────────────────────────────────────────────────────────────────\n"
    "# Editable runtime config. Managed by the application (UI / API / `make config`).\n"
    "# Edits here are persistent until the config is reset to its example template.\n"
    "# ─────────────────────────────────────────────────────────────────────────────\n"
)


def _strip_template_header(example_text: str) -> str:
    """Remove the generated banner from a ``*.example.yaml`` template body."""
    lines = example_text.splitlines(keepends=True)
    end = 0

    for idx, line in enumerate(lines):
        if _EXAMPLE_CONFIG_HEADER_MARK in line:
            end = idx + 1
            continue
        if end and line.lstrip().startswith("#"):
            end = idx + 1
            continue
        if end:
            break

    if end == 0:
        return example_text

    rest = lines[end:]
    while rest and rest[0].strip() == "":
        rest.pop(0)
    return "".join(rest)


def _content_for_real_from_example(example_text: str, real_path: Path) -> str:
    """Return the body to write into a real config file given its template."""
    if real_path.name == "rules.yaml":
        return _REAL_CONFIG_HEADER + "\nrules: []\n"
    return _REAL_CONFIG_HEADER + "\n" + _strip_template_header(example_text)


_FILE_SUFFIX_TO_EDITOR_FORMAT = {
    ".yaml": "yaml",
    ".yml": "yaml",
    ".json": "json",
    ".py": "python",
    ".toml": "toml",
}

# Friendly aliases for well-known single-file configs. Any id not in this map
# is treated as a relative path under ``backend/config/`` directly
# (e.g. ``pipelines/example_pipeline.yaml``).
_ID_ALIASES: dict[str, str] = {
    "rules": "rules.yaml",
    "mostly_ai": "mostly_ai.yaml",
    "general": "general.yaml",
    "evaluation": "evaluation.yaml",
    # "statistics" points at evaluation.yaml; consumers read the ``statistics:`` key.
    "statistics": "evaluation.yaml",
    "mode_presets": "mode_presets.yaml",
}


class ConfigNotFoundError(LookupError):
    """Raised when a requested config id does not map to a known template."""


class ConfigMissingError(FileNotFoundError):
    """Raised when the real ``*.yaml`` has not been created from its template.

    Thrown by read paths; callers should surface a message prompting
    ``make config`` (or a single-file bootstrap) to the user.
    """


class ConfigParseError(ValueError):
    """Raised when user-submitted content fails to parse as YAML/JSON."""


def _is_example_path(path: Path) -> bool:
    """Return ``True`` if ``path`` is a ``*.example.<suffix>`` template.

    Args:
        path (Path): Path to check.

    Returns:
        bool: True if it's a template path.
    """
    return path.stem.endswith(_EXAMPLE_SUFFIX) and path.suffix.lower() in _CONFIG_SUFFIXES


def _real_for_example(example_path: Path) -> Path:
    """Return the real-file path that corresponds to a template path.

    Args:
        example_path (Path): Path to the template file.

    Returns:
        Path: Path to the real file.
    """
    stem_without_example = example_path.stem[: -len(_EXAMPLE_SUFFIX)]
    return example_path.with_name(stem_without_example + example_path.suffix)


def _example_for_real(real_path: Path) -> Path:
    """Return the template path that corresponds to a real-file path.

    Args:
        real_path (Path): Path to the real file.

    Returns:
        Path: Path to the template file.
    """
    return real_path.with_name(real_path.stem + _EXAMPLE_SUFFIX + real_path.suffix)


def _scope_for_real_path(real_config_path: Path) -> ConfigScope:
    """Classify a real config file into the API scope taxonomy.

    Args:
        real_config_path (Path): Path to the real config file.

    Returns:
        ConfigScope: The assigned scope.
    """
    relative_path = real_config_path.relative_to(_CONFIG_ROOT)
    path_parts = relative_path.parts

    if real_config_path.name == "evaluation.yaml":
        return ConfigScope.EVALUATION
    if path_parts[0] == "pipelines":
        if len(path_parts) >= 2 and path_parts[1] == "rules":
            return ConfigScope.RULES
        return ConfigScope.PIPELINE
    if real_config_path.name in ("rules.yaml", "rules.py"):
        return ConfigScope.RULES
    return ConfigScope.ALL


def _real_relative_key_for(config_id: str) -> Path:
    """Map a config id to the relative path of its real file under ``backend/config/``.

    Args:
        config_id: The identifier for the config file.

    Returns:
        The relative path to the real config file.

    Raises:
        ConfigNotFoundError: If the id is outside the config tree, has an
            unsupported suffix, or does not have a committed ``*.example``
            template.
    """
    relpath_str = _ID_ALIASES.get(config_id, config_id)
    relative_path = Path(relpath_str)
    if relative_path.is_absolute() or any(part == ".." for part in relative_path.parts):
        raise ConfigNotFoundError(config_id)

    real_path = _CONFIG_ROOT / relative_path
    try:
        real_path.resolve().relative_to(_CONFIG_ROOT.resolve())
    except ValueError as exc:
        raise ConfigNotFoundError(config_id) from exc

    if real_path.suffix.lower() not in _CONFIG_SUFFIXES:
        raise ConfigNotFoundError(config_id)
    if not _example_for_real(real_path).is_file():
        raise ConfigNotFoundError(config_id)
    return relative_path


def list_configs(scope: ConfigScope = ConfigScope.ALL) -> list[ConfigFile]:
    """List editable config files that exist on disk.

    Walks real (non-example) config files under ``backend/config/`` and only
    returns entries that have actually been created (e.g. via ``make config``).
    Files without a corresponding ``*.example.*`` template are skipped.

    Args:
        scope (ConfigScope): Filter by logical scope. Defaults to ALL.

    Returns:
        list[ConfigFile]: List of discovered and validated configuration files.
    """
    if not _CONFIG_ROOT.exists():
        return []

    configs: list[ConfigFile] = []
    for real_path in _CONFIG_ROOT.rglob("*"):
        if not real_path.is_file() or _is_example_path(real_path):
            continue
        if real_path.suffix.lower() not in _CONFIG_SUFFIXES:
            continue
        if not _example_for_real(real_path).is_file():
            continue
        file_scope = _scope_for_real_path(real_path)
        if scope is not ConfigScope.ALL and file_scope is not scope:
            continue

        rel = real_path.relative_to(_CONFIG_ROOT)
        configs.append(
            ConfigFile(
                id=rel.as_posix(),
                path=str(real_path),
                name=real_path.name,
                size_bytes=real_path.stat().st_size,
                scope=file_scope,
                exists=True,
            )
        )
    configs.sort(key=lambda c: (c.scope.value, c.name.lower()))
    return configs


def example_path_for(config_id: str) -> Path:
    """Return the committed template path for a config id.

    Args:
        config_id (str): Identifier for the config.

    Returns:
        Path: Path to the template file.
    """
    return _example_for_real(_CONFIG_ROOT / _real_relative_key_for(config_id))


def real_path_for(config_id: str) -> Path:
    """Return the real-file path for a config id (may not exist yet).

    Args:
        config_id (str): Identifier for the config.

    Returns:
        Path: Path to the real file.
    """
    return _CONFIG_ROOT / _real_relative_key_for(config_id)


def resolve_config_path(config_id: str) -> Path:
    """Return the real-file path the application reads for a config id.

    Equivalent to :func:`real_path_for`; kept as the primary public name
    because callers throughout the codebase just want "the path currently in
    effect" and do not care about the template/real distinction.

    Args:
        config_id (str): Identifier for the config.

    Returns:
        Path: Path to the active real config file.
    """
    return real_path_for(config_id)


def config_exists(config_id: str) -> bool:
    """Return ``True`` when the real config file has been created.

    Args:
        config_id (str): Identifier for the config.

    Returns:
        bool: True if the file exists.
    """
    return real_path_for(config_id).is_file()


def read_config_text(config_id: str) -> str:
    """Read the real config file contents as UTF-8 text.

    Raises:
        ConfigMissingError: If the real file has not been created yet.
    """
    real = real_path_for(config_id)
    if not real.is_file():
        example = _example_for_real(real)
        raise ConfigMissingError(
            f"{real} not found. Run `make config` to create it from {example.name}, then edit it."
        )
    return real.read_text(encoding="utf-8")


def determine_config_scope(config_id: str) -> ConfigScope:
    """Return the API scope for a config identifier.

    Args:
        config_id (str): Identifier for the config.

    Returns:
        ConfigScope: The assigned scope.
    """
    return _scope_for_real_path(_CONFIG_ROOT / _real_relative_key_for(config_id))


def determine_editor_format_for_file_path(file_path: str) -> str:
    """Return the editor format token used by the frontend for a config file."""
    for suffix, editor_format in _FILE_SUFFIX_TO_EDITOR_FORMAT.items():
        if file_path.endswith(suffix):
            return editor_format
    return "yaml"


def validate_config_content_syntax(content: str, file_suffix: str) -> None:
    """Validate editable config content before writing.

    YAML and JSON are parsed to catch syntax errors early. Python and TOML
    files are accepted as raw text in this layer.

    Raises:
        ConfigParseError: If parsing fails for YAML or JSON.
    """
    suffix = file_suffix.lower()
    try:
        if suffix in (".yaml", ".yml"):
            yaml.safe_load(content)
        elif suffix == ".json":
            json.loads(content)
    except (yaml.YAMLError, json.JSONDecodeError) as exc:
        raise ConfigParseError(str(exc)) from exc


def write_config(config_id: str, content: str) -> Path:
    """Write validated content to the real config file for a config id.

    Creates the file if it did not exist yet — equivalent to bootstrapping a
    single config without invoking ``make config``.

    Raises:
        ConfigNotFoundError: If ``config_id`` has no committed template.
        ConfigParseError: If YAML/JSON syntax validation fails.
    """
    rel = _real_relative_key_for(config_id)
    validate_config_content_syntax(content, rel.suffix)
    real_path = _CONFIG_ROOT / rel
    real_path.parent.mkdir(parents=True, exist_ok=True)
    real_path.write_text(content, encoding="utf-8")
    return real_path


def bootstrap_frontend_env_local() -> dict[str, list[str]]:
    """Ensure ``frontend/.env.local`` exists from the committed example file.

    Non-destructive: if the local env file already exists, it is skipped.
    """
    created: list[str] = []
    skipped: list[str] = []

    if not _FRONTEND_ENV_EXAMPLE.is_file():
        return {"created": created, "skipped": skipped}

    frontend_rel = str(_FRONTEND_ENV_LOCAL.relative_to(_PROJECT_ROOT))
    if _FRONTEND_ENV_LOCAL.is_file():
        skipped.append(frontend_rel)
    else:
        _FRONTEND_ENV_LOCAL.parent.mkdir(parents=True, exist_ok=True)
        _FRONTEND_ENV_LOCAL.write_text(
            _FRONTEND_ENV_EXAMPLE.read_text(encoding="utf-8"), encoding="utf-8"
        )
        created.append(frontend_rel)

    return {"created": created, "skipped": skipped}


def migrate_real_config_headers() -> list[str]:
    """Rewrite real yamls whose top still carries the example template banner."""
    migrated: list[str] = []
    if not _CONFIG_ROOT.exists():
        return migrated
    for real in _CONFIG_ROOT.rglob("*.yaml"):
        if _is_example_path(real) or not real.is_file():
            continue
        text = real.read_text(encoding="utf-8")
        if _EXAMPLE_CONFIG_HEADER_MARK not in text:
            continue
        real.write_text(_REAL_CONFIG_HEADER + "\n" + _strip_template_header(text), encoding="utf-8")
        migrated.append(str(real.relative_to(_CONFIG_ROOT)))
    return migrated


def bootstrap_configs() -> dict[str, list[str]]:
    """Create real yaml files from templates, non-destructively.

    Mirrors ``make config``: copies each ``*.example.yaml`` to its real
    counterpart only when the real file does not already exist.

    Also ensures ``frontend/.env.local`` exists by copying
    ``frontend/env.example.local`` when needed, so both CLI and API bootstrap
    paths keep frontend/backend URL wiring consistent.
    """
    created: list[str] = []
    skipped: list[str] = []
    for example in sorted(_CONFIG_ROOT.rglob("*.example.yaml")):
        real = _real_for_example(example)
        rel = str(real.relative_to(_CONFIG_ROOT))
        if real.exists():
            skipped.append(rel)
        else:
            real.parent.mkdir(parents=True, exist_ok=True)
            real.write_text(
                _content_for_real_from_example(example.read_text(encoding="utf-8"), real),
                encoding="utf-8",
            )
            created.append(rel)

    frontend_result = bootstrap_frontend_env_local()
    created.extend(frontend_result["created"])
    skipped.extend(frontend_result["skipped"])

    return {"created": created, "skipped": skipped}


def clean_configs() -> dict[str, list[str]]:
    """Remove all real yaml files under ``backend/config/``, keeping templates.

    Mirrors ``make clean-config``.
    """
    removed: list[str] = []
    for real in sorted(_CONFIG_ROOT.rglob("*.yaml")):
        if _is_example_path(real):
            continue
        removed.append(str(real.relative_to(_CONFIG_ROOT)))
        real.unlink()
    return {"removed": removed}


def reset_config(config_id: str) -> Path:
    """Restore the real config file from its committed template.

    Overwrites the real file with the template contents. If the real file
    did not exist, it is created.
    """
    real = real_path_for(config_id)
    example = _example_for_real(real)
    real.parent.mkdir(parents=True, exist_ok=True)
    real.write_text(
        _content_for_real_from_example(example.read_text(encoding="utf-8"), real),
        encoding="utf-8",
    )
    return real


if __name__ == "__main__":
    import sys

    _cmd = sys.argv[1] if len(sys.argv) > 1 else ""
    if _cmd == "bootstrap":
        _r = bootstrap_configs()
        for _p in _r["created"]:
            print(f"  created:       {_p}")
        for _p in _r["skipped"]:
            print(f"  skip (exists): {_p}")
        print(f"Config bootstrap done. Created {len(_r['created'])}, skipped {len(_r['skipped'])}.")
        print("Edit backend/config/*.yaml (gitignored) — never the .example.yaml templates.")
    elif _cmd == "clean":
        _r = clean_configs()
        for _p in _r["removed"]:
            print(f"  removed: {_p}")
        print(
            f"clean-config done. Removed {len(_r['removed'])} real config file(s). Templates left untouched."
        )
    else:
        print("Usage: python -m backend.src.sessions.configs [bootstrap|clean]")
        sys.exit(1)
