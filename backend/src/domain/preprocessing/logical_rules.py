"""
Logical Rules System for Synthetic Data Generation.

This module implements a three-phase design pattern to guarantee consistency
of data generated by AI models (which often fail at deterministic logic):

1. PRE: Transformation of complex data into simplified representations (numeric/continuous)
    before training. Target columns are removed.
2. POST: Deterministic reconstruction of target columns from model predictions
    over auxiliary variables.
3. SANITY: Final validation to ensure business rules are met.
"""

import bisect
import json
from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from enum import Enum, auto
from typing import Any

import networkx as nx
import numpy as np
import pandas as pd
from backend.src.infrastructure.date_parsing import parse_dates
from backend.src.infrastructure.errors import (
    RelationshipNotDefinedError,
    RuleConcatenationError,
    RuleSuperimpositionError,
)
from backend.src.infrastructure.logging_config import get_logger

logger = get_logger(__name__)


class InteractionType(Enum):
    ISOLATED = auto()
    CONCATENATED = auto()
    SUPERIMPOSED = auto()


@dataclass
class LogicalRule(ABC):
    """
    Abstract base class to define a logical business rule.

    Args:
        table_origin (str): (Optional) Name of the source data table (context/reference).
        table_target (str): Name of the table where the rule applies (where the target is).
        rejection_sampling (bool): Whether this rule should be enforced via rejection sampling
    """

    table_origin: str = None
    table_target: str = None
    rejection_sampling: bool = False
    interaction_type: InteractionType = field(default=InteractionType.ISOLATED, init=False)

    @abstractmethod
    def apply_pre(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        Transforms original data into a format optimized for the model.
        It usually creates auxiliary columns and removes target columns.

        Args:
            df (pd.DataFrame): Original DataFrame (it may include columns from table_origin after
            the join performed by the Manager).

        Returns:
            pd.DataFrame: Transformed DataFrame.
        """
        pass


@dataclass
class DerivedColumnRule(LogicalRule, ABC):
    """Base class for derived columns computed from other columns (stratification).

    Derived columns are computed during PRE so they become part of training
    metadata, and recomputed during POST to enforce determinism.
    OPTIONALLY, the origin column can be dropped to force the model to only look at the stratified
    column. This column will then not be available in the synthetic data. For instance, if you would
    only like to use age buckets to generalize the model, you may chose to drop the original age.

    Args:
        - origin_col (str): Column used to compute the dervied column
        - aux_col (str): Name of derived column to create
        - drop_origin (bool): Whether to drop the origin column after computing the derived column.
            If True, the origin column will not be available in the synthetic data.
        - reconstruct_origin (bool): Whether to reconstruct the origin column during POST if it
            was dropped during PRE.
    """

    aux_col: str = None
    origin_col: str = None
    drop_origin: bool = False
    reconstruct_origin: bool = False
    _origin_dropped: bool = field(default=False, init=False, repr=False)

    def _require_aux(self) -> None:
        if self.aux_col is None:
            raise ValueError("DerivedColumnRule requires 'aux_col'.")

    def _drop_origin_column(self, df: pd.DataFrame, origin_col: str) -> pd.DataFrame:
        if self.drop_origin and origin_col in df.columns:
            return df.drop(columns=[origin_col])
        return df

    @abstractmethod
    def _compute_derived(self, df: pd.DataFrame) -> pd.Series:
        """Computes the derived column based on the origin column(s)."""
        pass

    def _reconstruct_origin(self, df: pd.DataFrame) -> pd.Series | None:
        """Reconstructs the origin column from derived inputs when possible."""
        return None

    def apply_pre(self, df: pd.DataFrame) -> pd.DataFrame:
        df[self.aux_col] = self._compute_derived(df)
        if self.drop_origin and self.origin_col in df.columns:
            self._origin_dropped = True
        return self._drop_origin_column(df, self.origin_col)

    def apply_post(self, df: pd.DataFrame) -> pd.DataFrame:
        if self.origin_col not in df.columns:
            if self.drop_origin and self._origin_dropped and self.reconstruct_origin:
                reconstructed = self._reconstruct_origin(df)
                if reconstructed is not None:
                    df[self.origin_col] = reconstructed
                else:
                    logger.warning(
                        "Origin column '%s' missing for %s on '%s'; unable to reconstruct origin.",
                        self.origin_col,
                        type(self).__name__,
                        self.table_target,
                    )
            elif not self.drop_origin:
                logger.warning(
                    "Origin column '%s' missing for %s on '%s'; cannot recompute derived column '%s'.",
                    self.origin_col,
                    type(self).__name__,
                    self.table_target,
                    self.aux_col,
                )
            return df
        df[self.aux_col] = self._compute_derived(df)
        return df

    @abstractmethod
    def sanity_check(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        Verifies that final data satisfies the strict rule.

        Args:
            df (pd.DataFrame): Final synthetic DataFrame.

        Returns:
            pd.DataFrame: Subset of rows that do NOT satisfy the rule (empty if everything is OK).
        """
        pass


@dataclass
class LogicalRuleManager:
    """
    Orchestrator that manages the rule collection and its sequential execution.

    Maintains the state of rules required for reconstruction.

    Arguments are populated through add_rule() (arg 'rule') and through
    apply_all_pre() arguments (arg 'relationships').

    Args:
        rules (List[LogicalRule]): List of registered rules.
        relationships (Dict): PK/FK metadata dictionary.
                              Format: {('child_table', 'parent_table'): [('fk_col', 'pk_col'), ...]}

    Returns:
        LogicalRuleManager: Dataclass instance.
    """

    rules: list[LogicalRule] = field(default_factory=list)
    relationships: dict[tuple[str, str], list[tuple[str, str]]] | None = field(default=None)
    rejection_sampling_config: dict[str, Any] = field(default_factory=dict)
    date_formats: dict[str, dict[str, str | None]] = field(default_factory=dict)

    def add_rule(self, rule: LogicalRule) -> bool:
        """Checks rule conflicts. If no superimpositions exist,
        registers a new rule in the manager.

        Args:
            rule (LogicalRule): Rule instance to add.
        Returns:
            bool: True if the rule was added successfully, False if it was rejected
        """
        try:
            should_add = self._detect_rule_interactions(
                rule
            )  # throws error if superimposition detected
        except RuleSuperimpositionError:
            logger.error("Failed to add rule: Rule Superimposition not allowed. Skipping")
            return False
        if should_add is False:
            return True
        self.rules.append(rule)
        return True

    def _is_inequality_rule(self, rule: LogicalRule) -> bool:
        return isinstance(rule, (DateInequalityRule, NumericInequalityRule))

    def _get_qualified_target(self, rule: LogicalRule) -> str | None:
        return self._qualify_col(rule.table_target, getattr(rule, "target_col", None))

    def _get_qualified_origin(self, rule: LogicalRule) -> str | None:
        return self._qualify_col(
            rule.table_origin or rule.table_target, getattr(rule, "origin_col", None)
        )

    def _collect_inequality_component(
        self, rules: list[LogicalRule], start_rule: LogicalRule
    ) -> list[LogicalRule]:
        adjacency: dict[int, set[int]] = {idx: set() for idx in range(len(rules))}

        for idx, left in enumerate(rules):
            left_target = self._get_qualified_target(left)
            left_origin = self._get_qualified_origin(left)
            for right_idx in range(idx + 1, len(rules)):
                right = rules[right_idx]
                right_target = self._get_qualified_target(right)
                right_origin = self._get_qualified_origin(right)

                shares_target = left_target and right_target and left_target == right_target
                left_depends_on_right = left_target and right_origin and left_target == right_origin
                right_depends_on_left = right_target and left_origin and right_target == left_origin

                if shares_target or left_depends_on_right or right_depends_on_left:
                    adjacency[idx].add(right_idx)
                    adjacency[right_idx].add(idx)

        component: list[LogicalRule] = []
        start_idx = rules.index(start_rule)
        queue = [start_idx]
        seen: set[int] = set()
        while queue:
            current = queue.pop()
            if current in seen:
                continue
            seen.add(current)
            component.append(rules[current])
            queue.extend(adjacency.get(current, set()) - seen)

        return component

    def _apply_inequality_chain_flip(self, component: list[LogicalRule]) -> None:
        if any(rule.interaction_type == InteractionType.CONCATENATED for rule in component):
            raise RuleSuperimpositionError(
                "Cannot resolve superimposition by flipping: already concatenated rule in chain."
            )
        prospective_targets: list[str] = []
        for rule in component:
            if getattr(rule, "_flipped", False):
                qualified_target = self._get_qualified_target(rule)
                if not qualified_target:
                    raise RuleSuperimpositionError(
                        f"Cannot resolve superimposition by flipping: rule {type(rule).__name__} "
                        f"on '{rule.table_target}' has no target column."
                    )
                prospective_targets.append(qualified_target)
                continue

            origin = self._get_qualified_origin(rule)
            if not origin:
                raise RuleSuperimpositionError(
                    f"Cannot resolve superimposition by flipping: rule {type(rule).__name__} "
                    f"on '{rule.table_target}' has no origin column."
                )
            prospective_targets.append(origin)

        if len(prospective_targets) != len(set(prospective_targets)):
            raise RuleSuperimpositionError(
                "Cannot resolve superimposition by flipping: origin fan-out would be created."
            )

        for rule in component:
            rule.interaction_type = InteractionType.SUPERIMPOSED
            if not getattr(rule, "_flipped", False):
                rule.flip()

        ordered = sorted(
            component,
            key=lambda rule: (
                rule.table_target or "",
                getattr(rule, "target_col", "") or "",
                getattr(rule, "origin_col", "") or "",
                type(rule).__name__,
            ),
        )
        for idx, rule in enumerate(ordered, start=1):
            rule.aux_col = f"{rule.target_col}_flipped_{idx}"

    def _detect_rule_interactions(self, new_rule: LogicalRule) -> bool:
        """Checks for both superimposition and concatenation rule conflicts/interactions.
        Superimpositions occur when both rules have the same target table and column.
            If any are detected, a RuleSuperimpositionError is raised. These are currently
            not allowed to ensure clear and deterministic rule application.
        Concatenation rules are when the target of one rule serves as the origin for another,
            creating a dependency chain. These are allowed, and are sorted before applying PRE.
            As such, we save them in a list to later be sorted.

        Rejection sampling rules can rely on previous rules, but dont create new columns. If any
        concatenation rules, we throw them at the end.

        If no interactions are detected, the rule is considered an independent, isolated rule.

        Args:
            new_rule (LogicalRule): The new rule to check against existing rules.
        Returns:
            bool: True if the rule should be added, False if it was merged with an existing rule (SemanticConsistencyRule)
        Throws:
            RuleSuperimpositionError: If an unresolvable superimposition is detected between the new rule and an existing rule.
        """

        for existing_rule in self.rules:
            shares_target = (
                existing_rule.table_target == new_rule.table_target
                and getattr(existing_rule, "target_col", None) is not None
                and getattr(new_rule, "target_col", None) is not None
                and existing_rule.target_col == new_rule.target_col
            )
            # A rejection-sampling rule never writes/reconstructs a column: its PRE
            # and POST are skipped and it only drops rows that violate the
            # constraint. So a pair involving a rejection rule is neither a
            # superimposition (sharing a target is fine — the other rule sets the
            # value, the rejection rule filters what remains) nor a concatenation
            # (it produces nothing and needs no PRE ordering). Skip both so the rule
            # is registered as isolated instead of being silently dropped.
            rejection_involved = bool(
                getattr(existing_rule, "rejection_sampling", False)
                or getattr(new_rule, "rejection_sampling", False)
            )
            if rejection_involved:
                continue
            if shares_target:
                # superimposition detected

                if (
                    isinstance(existing_rule, SemanticConsistencyRule)
                    and isinstance(new_rule, SemanticConsistencyRule)
                    and type(existing_rule)
                    is type(new_rule)  # make sure they use the same semantic consistency logic
                ):
                    for group_col in new_rule._get_group_cols():
                        existing_rule.add_group_key(group_col)

                    # we dont need to mark as superimposed since they will be merged
                    # existing_rule.interaction_type = InteractionType.SUPERIMPOSED
                    logger.info(
                        "Semantic rule superimposition detected for '%s'; merged group keys into existing rule.",
                        new_rule.target_col,
                    )
                    return False

                # not allowed EXCEPT for numeric/date inequality rules, which can be flipped
                if (
                    isinstance(existing_rule, DateInequalityRule)
                    and isinstance(new_rule, DateInequalityRule)
                ) or (
                    isinstance(existing_rule, NumericInequalityRule)
                    and isinstance(new_rule, NumericInequalityRule)
                ):
                    # Only forced rules participate in a flip; rejection rules don't
                    # write their target so they're never part of the chain. (Both
                    # ``existing_rule`` and ``new_rule`` are already forced here — a
                    # rejection rule would have skipped this block above.)
                    rule_type = type(new_rule)
                    candidates = [
                        rule
                        for rule in self.rules
                        if isinstance(rule, rule_type) and not rule.rejection_sampling
                    ] + [new_rule]
                    component = self._collect_inequality_component(candidates, new_rule)

                    self._apply_inequality_chain_flip(component)
                    return True

                raise RuleSuperimpositionError(
                    f"Rule superimposition detected: New rule {type(new_rule).__name__} on "
                    f"'{new_rule.table_target}' column '{new_rule.target_col}' overlaps with existing "
                    f"rule {type(existing_rule).__name__} on the same target."
                )
            new_sources = self._get_rule_source_cols(new_rule)
            new_outputs = self._get_rule_produced_cols(new_rule)
            existing_sources = self._get_rule_source_cols(existing_rule)
            existing_outputs = self._get_rule_produced_cols(existing_rule)
            existing_removals = self._get_rule_removed_cols(existing_rule)

            depends_on_existing = bool(new_sources & (existing_outputs | existing_removals))
            existing_depends_on_new = bool(existing_sources & new_outputs)

            if depends_on_existing or existing_depends_on_new:
                logger.info(
                    f"Rule concatenation detected between {type(new_rule).__name__} on "
                    f"'{new_rule.table_target}' and {type(existing_rule).__name__} on "
                    f"'{existing_rule.table_target}'."
                )
                existing_rule.interaction_type = InteractionType.CONCATENATED
                new_rule.interaction_type = InteractionType.CONCATENATED

        if (
            new_rule.interaction_type != InteractionType.CONCATENATED
            and new_rule.interaction_type != InteractionType.SUPERIMPOSED
        ):
            logger.info(
                f"No interactions detected for new rule {type(new_rule).__name__} on "
                f"'{new_rule.table_target}'. Registered as an independent rule."
            )
            new_rule.interaction_type = InteractionType.ISOLATED
        return True

    def _sort_concat_rules(self, columnNames: set[str]) -> list[LogicalRule]:
        """Sorts concatenation rules based on their dependencies to ensure correct application order
        during PRE. Raises an error if there does not exist a possible order. Not all rules are
        connected.

            Args:
                columnNames (set[str]): Set of all ORIGINAL (non-derived) column names across all
                tables in the form "table_name.column_name", used to validate rule dependencies.
        """
        # Build a mutable working list in the same order as provided.
        rules = [
            rule
            for rule in self.rules
            if rule.interaction_type != InteractionType.ISOLATED and not rule.rejection_sampling
        ]
        rejection_rules = [
            rule
            for rule in self.rules
            if rule.interaction_type != InteractionType.ISOLATED and rule.rejection_sampling
        ]

        if not rules:
            return []

        # Prune rules that reference missing columns, cascading until stable.
        original_cols = set(columnNames)
        removed_rules = True
        while removed_rules:
            removed_rules = False
            produced_cols: set[str] = set()
            for rule in rules:
                produced_cols.update(self._get_rule_produced_cols(rule))

            filtered_rules: list[LogicalRule] = []
            for rule in rules:
                missing_sources = {
                    source_col
                    for source_col in self._get_rule_source_cols(rule)
                    if source_col not in original_cols and source_col not in produced_cols
                }
                target_col = getattr(rule, "target_col", None)
                qualified_target = (
                    self._qualify_col(rule.table_target, target_col) if target_col else None
                )
                missing_target = (
                    qualified_target is not None
                    and qualified_target not in original_cols
                    and qualified_target not in produced_cols
                )
                if missing_sources:
                    logger.warning(
                        "Skipping rule %s on '%s' due to missing source columns: %s",
                        type(rule).__name__,
                        rule.table_target,
                        sorted(missing_sources),
                    )
                    removed_rules = True
                    continue
                if missing_target:
                    logger.warning(
                        "Skipping rule %s on '%s' due to missing target column: %s",
                        type(rule).__name__,
                        rule.table_target,
                        qualified_target,
                    )
                    removed_rules = True
                    continue
                filtered_rules.append(rule)

            rules = filtered_rules

        if not rules:
            return rejection_rules

        graph = nx.DiGraph()
        graph.add_nodes_from(range(len(rules)))

        # Build maps of produced columns to their producer rule indices.
        produced_by: dict[str, int] = {}
        for idx, rule in enumerate(rules):
            for produced_col in self._get_rule_produced_cols(rule):
                if produced_col in produced_by:
                    raise RuleConcatenationError(
                        f"Rule ordering error: column '{produced_col}' produced by multiple rules."
                    )
                produced_by[produced_col] = idx

        for idx, rule in enumerate(rules):
            for source_col in self._get_rule_source_cols(rule):
                if source_col in produced_by:
                    producer_idx = produced_by[source_col]
                    if producer_idx != idx:
                        graph.add_edge(producer_idx, idx)

        # If a rule removes a column that another rule uses, enforce consumer -> remover ordering.
        removed_by: dict[str, int] = {}
        for idx, rule in enumerate(rules):
            for removed_col in self._get_rule_removed_cols(rule):
                removed_by[removed_col] = idx

        for idx, rule in enumerate(rules):
            for source_col in self._get_rule_source_cols(rule):
                remover_idx = removed_by.get(source_col)
                if remover_idx is not None and remover_idx != idx:
                    graph.add_edge(idx, remover_idx)

        try:
            nx.find_cycle(graph, orientation="original")
        except nx.NetworkXNoCycle:
            pass
        else:
            raise RuleConcatenationError(
                "Rule sorting failed: unresolvable dependency cycle detected in concatenated rules."
            )

        sorted_indices = list(
            nx.algorithms.dag.lexicographical_topological_sort(graph, key=lambda x: x)
        )
        rules = [rules[idx] for idx in sorted_indices]

        # add back rejection sampling rules at end
        rules.extend(rejection_rules)

        # log all rules for debugging
        logger.debug("Concatenation rules sorted in the following order:")
        for rule in rules:
            logger.debug(
                f"{type(rule).__name__} on '{rule.table_target}' (origin: '{rule.table_origin}')"
            )
        return rules

    def _qualify_col(self, table: str | None, col: str | None) -> str | None:
        """Utility to qualify a column name with its table for consistent identification across rules.
        Only used in the context of rule interaction detection and sorting, not in actual DataFrame
        operations, where we rely on the original column names.

        Args:
            table (str | None): Table name to qualify with (can be None for unqualified).
            col (str | None): Column name to qualify.
        """
        if not col:
            return None
        return f"{table}.{col}" if table else col

    def _get_rule_source_cols(self, rule: LogicalRule) -> set[str]:
        """Get the set of source columns for a given rule.
        This includes both explicitly defined origin/source columns and any columns from the origin
        table that are used in the rule's logic (heuristically determined based on rule type
        and attributes).

        Args:
            rule (LogicalRule): The rule for which to extract source columns.
        """
        cols: set[str] = set()
        if isinstance(rule, DerivedColumnRule):
            cols.add(self._qualify_col(rule.table_target, rule.origin_col))
            return {col for col in cols if col}
        origin_col = getattr(rule, "origin_col", None)
        if origin_col:
            cols.add(self._qualify_col(rule.table_origin or rule.table_target, origin_col))
        source_col = getattr(rule, "source_col", None)
        if source_col:
            cols.add(self._qualify_col(rule.table_origin or rule.table_target, source_col))
        return {col for col in cols if col}

    def _get_rule_produced_cols(self, rule: LogicalRule) -> set[str]:
        """Get the set of columns produced by a given rule in PRE..
        Args:
            rule (LogicalRule): The rule for which to extract produced columns.
        """
        cols: set[str] = set()
        aux_col = getattr(rule, "aux_col", None)
        if aux_col:
            cols.add(self._qualify_col(rule.table_target, aux_col))
        return {col for col in cols if col}

    def _get_rule_removed_cols(self, rule: LogicalRule) -> set[str]:
        """Get the set of columns removed by a given rule in PRE.
        Args:
            rule (LogicalRule): The rule for which to extract removed columns.
        """
        target_col = getattr(rule, "target_col", None)
        if target_col:
            return {self._qualify_col(rule.table_target, target_col)}
        part_cols = getattr(rule, "part_cols", None)
        if isinstance(part_cols, dict) and part_cols:
            return {self._qualify_col(rule.table_target, col) for col in part_cols.values() if col}
        return set()

    def _find_join_path(self, start_table: str, end_table: str) -> list[dict]:
        from collections import deque

        if not self.relationships:
            logger.warning(
                "Cannot resolve join path from '%s' to '%s': no relationships are loaded.",
                start_table,
                end_table,
            )
            return []

        queue = deque([(start_table, [])])
        visited = {start_table}

        while queue:
            current_table, path = queue.popleft()
            if current_table == end_table:
                logger.debug(
                    f"Join path found from '{start_table}' to '{end_table}': {[step['target_table'] for step in path]}"
                )
                return path

            for (child, parent), list_configs in self.relationships.items():
                if child == current_table and parent not in visited:
                    visited.add(parent)
                    join_config = list_configs[0]
                    queue.append(
                        (
                            parent,
                            path
                            + [
                                {
                                    "target_table": parent,
                                    "left_col": join_config[0],
                                    "right_col": join_config[1],
                                }
                            ],
                        )
                    )
                elif parent == current_table and child not in visited:
                    visited.add(child)
                    join_config = list_configs[0]
                    queue.append(
                        (
                            child,
                            path
                            + [
                                {
                                    "target_table": child,
                                    "left_col": join_config[1],
                                    "right_col": join_config[0],
                                }
                            ],
                        )
                    )
        logger.warning(f"No join path found for '{start_table}' to '{end_table}'")
        return []

    def _get_joined_view(
        self,
        rule: LogicalRule,
        data_dict: dict[str, pd.DataFrame],
        include_target_row_id: bool = False,
        target_row_id_col: str = "__target_row_id",
    ) -> pd.DataFrame:
        """Creates a temporary view with data from the reference table if needed."""
        main_df = data_dict[rule.table_target]

        if include_target_row_id and target_row_id_col in main_df.columns:
            raise ValueError(
                f"Target row id column '{target_row_id_col}' already exists in '{rule.table_target}'."
            )

        if include_target_row_id:
            main_df = main_df.copy()
            main_df[target_row_id_col] = main_df.index

        if not rule.table_origin or rule.table_origin == rule.table_target:
            logger.debug(
                f"No join needed for rule on '{rule.table_target}' (no origin or same as target)."
            )
            return main_df if include_target_row_id else main_df.copy()

        path = self._find_join_path(rule.table_target, rule.table_origin)
        if not path:
            raise RelationshipNotDefinedError(
                f"No relationship defined between '{rule.table_target}' and '{rule.table_origin}'"
            )

        merged = main_df
        logger.debug(f"Creating joined view for rule on '{rule.table_target}'")
        # Track active names in `merged` for columns that might dictate multi-hop relationships.
        # col_map[table_name][original_col] -> current_col_in_merged
        col_map = {rule.table_target: {c: c for c in merged.columns}}
        current_left_table = rule.table_target

        for join_info in path:
            target_table = join_info["target_table"]
            origin_df = data_dict[target_table].copy()

            orig_left = join_info["left_col"]
            orig_right = join_info["right_col"]

            actual_left = col_map.get(current_left_table, {}).get(orig_left, orig_left)

            # debug log all columns
            logger.debug(
                f"Joining '{current_left_table}' (col '{actual_left}') with '{target_table}' (col '{orig_right}'). "
            )

            # Explicitly avoid key dropping and duplication by proactively renaming overlapping columns
            rename_dict = {}
            for col in origin_df.columns:
                new_col = col
                if new_col in merged.columns:
                    new_col += "_origin"
                    while new_col in merged.columns:
                        logger.debug(
                            f"Renaming column '{col}' from '{target_table}' to '{new_col}' to avoid collision in merged view."
                        )
                        new_col += "_origin"
                rename_dict[col] = new_col

            # Important bugfix: force renaming the right join key if it identical to actual_left,
            # otherwise pd.merge unifies them and drops the right-side values!
            if rename_dict[orig_right] == actual_left:
                new_right = actual_left + "_origin"
                while new_right in merged.columns:
                    new_right += "_origin"
                    logger.debug(
                        f"Renaming column '{orig_right}' from '{target_table}' to '{new_right}' to avoid collision with left join key."
                    )
                rename_dict[orig_right] = new_right

            origin_df.rename(columns=rename_dict, inplace=True)
            actual_right = rename_dict[orig_right]

            merged = pd.merge(
                merged,
                origin_df,
                left_on=actual_left,
                right_on=actual_right,
                how="left",
                # Pass empty suffixes since we already fully resolved collisions
                suffixes=("", ""),
            )

            col_map[target_table] = {col: rename_dict[col] for col in rename_dict}
            current_left_table = target_table

        return merged

    def _strip_origin_columns(
        self, joined_df: pd.DataFrame, rule: LogicalRule, data_dict: dict, keep_columns: set
    ) -> pd.DataFrame:
        """
        Keeps original columns from the target table and new auxiliary columns,
        removing only those brought by joining the source table (or tables from the join path).
        """
        if (
            not rule.table_origin
            or rule.table_origin not in data_dict
            or rule.table_origin == rule.table_target
        ):
            logger.debug(
                f"No origin columns to strip for rule on '{rule.table_target}' (no origin or same as target)."
            )
            return joined_df

        path = self._find_join_path(rule.table_target, rule.table_origin)
        if not path:
            logger.debug(
                f"No join path found for rule on '{rule.table_target}' (origin: '{rule.table_origin}')."
            )
            return joined_df

        origin_columns = set()
        for join_info in path:
            origin_columns.update(set(data_dict[join_info["target_table"]].columns))

        preserved_columns = {getattr(rule, "target_col", None)}
        for join_info in path:
            preserved_columns.add(join_info["left_col"])

        cols_to_keep = []
        for col_name in joined_df.columns:
            # Handle multiple "_origin" suffixes for multi-hop chains
            base_col = col_name
            while base_col.endswith("_origin"):
                base_col = base_col[: -len("_origin")]

            is_origin_collision = base_col in origin_columns and base_col != col_name
            is_unsuffixed_origin = col_name in origin_columns and col_name not in preserved_columns

            if is_origin_collision or is_unsuffixed_origin:
                logger.debug(
                    f"Stripping origin column '{col_name}' from joined view for rule on '{rule.table_target}'."
                )
                continue

            cols_to_keep.append(col_name)
            logger.debug(f"Keeping column '{col_name}' in joined view.")

        # add keep_columns to joined_df
        # these are target columns from other rules
        for col in keep_columns:
            if col not in cols_to_keep and col in joined_df.columns:
                logger.debug(
                    f"Adding column '{col}' to joined view due to its role in subsequent rules."
                )
                cols_to_keep.append(col)
            elif col not in joined_df.columns:
                logger.warning(
                    f"Column '{col}' specified to keep but not found in joined DataFrame for rule on '{rule.table_target}'."
                )

        return joined_df[cols_to_keep]

    def apply_all_pre(
        self,
        data_dict: dict[str, pd.DataFrame],
        relationships: dict[tuple[str, str], list[tuple[str, str]]],
    ) -> dict[str, pd.DataFrame]:
        """
        Executes the preprocessing phase of all registered rules.

        Args:
            data_dict (Dict[str, pd.DataFrame]): Dictionary {table_name: dataframe}.
            relationships (Dict): PK/FK metadata dictionary.
                                  Format: {('child_table', 'parent_table'): [('fk_col', 'pk_col'), ...]}

        Returns:
            Dict[str, pd.DataFrame]: Dictionary of transformed data.
        """
        self.relationships = relationships
        # Runtime attribute (not a dataclass field, so it never serializes):
        # advisory warnings emitted by rules during PRE (e.g. a constraint whose
        # precision differs from the column's), surfaced on the BRC card.
        self.pre_warnings: list[dict[str, Any]] = []

        # filter out isolated rules that reference non-existant source or target columns
        # concat and superimposed rules are handled within sorting function
        filtered_isolated_rules: list[LogicalRule] = []
        for rule in [
            rule for rule in self.rules if rule.interaction_type == InteractionType.ISOLATED
        ]:
            if rule.table_target in data_dict:
                target_col = getattr(rule, "target_col", None)
                if target_col and target_col not in data_dict[rule.table_target].columns:
                    logger.warning(
                        "Removing isolated rule %s on '%s' due to missing target column '%s'.",
                        type(rule).__name__,
                        rule.table_target,
                        target_col,
                    )
                    continue
            # ``origin_col`` may live in either ``table_origin`` or
            # ``table_target``: ``DerivedColumnRule`` subclasses (e.g.
            # ``DateToAgeRule``) repurpose ``table_origin`` to point at the
            # table that owns the *reference* column in some cross-table
            # layouts, in which case ``origin_col`` actually lives in
            # ``table_target``. Accept either to avoid dropping otherwise-valid
            # rules.
            origin_col = getattr(rule, "origin_col", None)
            if origin_col:
                candidate_tables = [
                    t for t in (rule.table_origin, rule.table_target) if t and t in data_dict
                ]
                if candidate_tables and all(
                    origin_col not in data_dict[t].columns for t in candidate_tables
                ):
                    logger.warning(
                        "Removing isolated rule %s on '%s' due to missing origin column '%s'.",
                        type(rule).__name__,
                        rule.table_target,
                        origin_col,
                    )
                    continue
            filtered_isolated_rules.append(rule)

        existsConcatRules = any(
            rule.interaction_type != InteractionType.ISOLATED for rule in self.rules
        )
        if existsConcatRules:
            logger.info("Sorting concatenation rules based on detected dependencies.")
            # put column names into form {table_name.column_name}
            columnNames = set()
            for table, df in data_dict.items():
                for col in df.columns:
                    columnNames.add(f"{table}.{col}")
            try:
                concatRules = self._sort_concat_rules(columnNames)
                self.rules = filtered_isolated_rules + concatRules
            except RuleConcatenationError as e:
                logger.error(
                    f"Error sorting concatenation rules: {str(e)}. Skipping all concatenation rules."
                )
                self.rules = filtered_isolated_rules
        else:
            self.rules = filtered_isolated_rules

        processed_data = data_dict
        empty_set = set()
        for rule in self.rules:
            if rule.rejection_sampling:
                logger.info(
                    "Skipping PRE for rejection-sampling rule: %s on %s",
                    type(rule).__name__,
                    rule.table_target,
                )
                if isinstance(rule, SemanticConsistencyRule):
                    view_df = self._get_joined_view(rule, processed_data)
                    rule._generate_valid_combinations(view_df)
                continue
            if rule.table_target in processed_data:
                logger.info(
                    f"Applying PRE rule: {type(rule).__name__} on {rule.table_target} (Origin: {rule.table_origin})"
                )

                view_df = self._get_joined_view(rule, processed_data)

                # always execute apply_pre so the rule learns metadata (state)
                transformed_view = rule.apply_pre(view_df)
                warning = getattr(rule, "_pre_warning", None)
                if warning:
                    self.pre_warnings.append(warning)

                processed_data[rule.table_target] = self._strip_origin_columns(
                    transformed_view, rule, processed_data, keep_columns=empty_set
                )

            else:
                logger.warning(f"Skipped PRE: Table '{rule.table_target}' not found.")
        return processed_data

    def apply_foreign_key_consistency_pre(
        self, data_dict: dict[str, pd.DataFrame]
    ) -> dict[str, pd.DataFrame]:
        """Apply the PRE phase of ``ForeignKeysConsistencyRule`` rules only.

        These rules drop a redundant non-context FK column that POST later
        rebuilds from its context parent. Unlike the other rules, they must run
        even when full PRE was already applied upstream (``reapply=False``):
        their targets are only known once context relationships are resolved
        (at training time, not at inspection time), so they are added to the
        manager too late to be part of the cached, pre-processed data. If the
        redundant FK is left in, the synthesis engine treats it as a non-context
        relationship and resolves it with a slow per-row FK-matching model during
        ``FINALIZE_GENERATION``. Dropping it here avoids that entirely; POST still
        reconstructs the column for the final output.

        PRE for these rules only removes ``target_col``, so no parent join is
        needed; it is safe to apply per table.
        """
        processed_data = data_dict.copy()
        for rule in self.rules:
            if not isinstance(rule, ForeignKeysConsistencyRule):
                continue
            table = rule.table_target
            if table in processed_data and rule.target_col in processed_data[table].columns:
                logger.info(
                    "Applying PRE (FK consistency): dropping redundant non-context FK "
                    "'%s' from '%s' (reconstructed from %s in POST).",
                    rule.target_col,
                    table,
                    rule.table_origin,
                )
                processed_data[table] = rule.apply_pre(processed_data[table])
        return processed_data

    def apply_all_post(self, data_dict: dict[str, pd.DataFrame]) -> dict[str, pd.DataFrame]:
        """
        Executes the reconstruction phase.
        IMPORTANT: It runs in reverse order (LIFO) to handle dependencies between rules.

        Args:
            data_dict (Dict[str, pd.DataFrame]): Raw synthetic data.

        Returns:
            Dict[str, pd.DataFrame]: Reconstructed synthetic data.
        """
        processed_data = data_dict
        # Runtime attribute (not a dataclass field, so it never serializes):
        # structured degradation warnings emitted by rules during this POST
        # pass, surfaced in the simulation report. Reset on every call because
        # rejection sampling re-runs POST once per attempt.
        self.post_warnings: list[dict[str, Any]] = []
        preserve_columns = set()
        derived_rules: list[DerivedColumnRule] = []
        standard_rules: list[LogicalRule] = []

        for rule in self.rules:
            if isinstance(rule, DerivedColumnRule):
                derived_rules.append(rule)
            else:
                standard_rules.append(rule)

        for rule in reversed(standard_rules):
            # define columns specifically outputed by rules so that we dont delete them later on
            # applies for multiple fk relations to a single table
            # (only applies to foreign key consistency rules)
            if rule.rejection_sampling:
                logger.info(
                    "Skipping POST for rejection-sampling rule: %s on %s",
                    type(rule).__name__,
                    rule.table_target,
                )
                continue
            if rule.table_target in processed_data:
                logger.info(f"Applying POST rule: {type(rule).__name__} on {rule.table_target}")

                # 1. Create view (join if needed for reconstruction)
                view_df = self._get_joined_view(rule, processed_data)

                # 2. Apply rule
                reconstructed_view = rule.apply_post(view_df)
                self._collect_post_warning(rule)

                # 3. Clean and save
                processed_data[rule.table_target] = self._strip_origin_columns(
                    reconstructed_view, rule, processed_data, preserve_columns
                )
                if isinstance(rule, ForeignKeysConsistencyRule):
                    logger.debug(
                        f"Adding '{rule.target_col}' to preserve_columns for subsequent POST applications due to its role in FK consistency."
                    )
                    preserve_columns.add(rule.target_col)

            else:
                logger.warning(f"Skipped POST: Table '{rule.table_target}' not found.")

        for rule in derived_rules:
            if rule.rejection_sampling:
                logger.info(
                    "Skipping POST for rejection-sampling derived rule: %s on %s",
                    type(rule).__name__,
                    rule.table_target,
                )
                continue
            if rule.table_target in processed_data:
                logger.info(
                    f"Applying POST derived rule: {type(rule).__name__} on {rule.table_target}"
                )
                view_df = self._get_joined_view(rule, processed_data)
                reconstructed_view = rule.apply_post(view_df)
                self._collect_post_warning(rule)
                processed_data[rule.table_target] = self._strip_origin_columns(
                    reconstructed_view, rule, processed_data, preserve_columns
                )
            else:
                logger.warning(f"Skipped POST derived rule: Table '{rule.table_target}' not found.")
        return processed_data

    def _collect_post_warning(self, rule: LogicalRule) -> None:
        """Move a rule's degradation warning (if any) into ``post_warnings``."""
        warning = getattr(rule, "_post_warning", None)
        if warning:
            self.post_warnings.append(warning)

    def run_rules_sanity_checks(
        self,
        data_dict: dict[str, pd.DataFrame],
        rules: list[LogicalRule] | None = None,
        unenforced_rejection: bool = False,
    ) -> pd.DataFrame:
        """Runs validations for rules and returns a detailed report.

        Each rule produces exactly one row in the report with its
        individual result (PASS, FAIL, or SKIPPED).

        Args:
            data_dict (Dict[str, pd.DataFrame]): Final data to validate.
            unenforced_rejection (bool): When True, rejection-sampling rules were
                *not* applied this run (no subject sample size, so the engine
                produced a single uncontrolled batch). Report those rules as
                SKIPPED — they were never enforced, so validating them would
                misleadingly show PASS/FAIL on data the rule never shaped.

        Returns:
            pd.DataFrame: Report with columns [check, rule, table, status,
                failed_rows, total_rows, details].
        """
        rows: list[dict] = []

        logger.info("\n--- EXECUTING SANITY CHECKS ---")

        rules_to_check = rules if rules is not None else self.rules

        for rule in rules_to_check:
            rule_name = type(rule).__name__

            def _identity(r: LogicalRule) -> dict:
                """Extract per-rule identifying fields so the report can reconstruct labels."""
                _str_or_none = lambda v: str(v) if v is not None else None
                return {
                    "table_origin": r.table_origin,
                    "origin_col": getattr(r, "origin_col", None),
                    "target_col": getattr(r, "target_col", None),
                    "source_col": getattr(r, "source_col", None),
                    "aux_col": getattr(r, "aux_col", None),
                    "canonical_col": getattr(r, "canonical_col", None),
                    "part_cols": json.dumps(getattr(r, "part_cols", None) or {}),
                    "constraint": _str_or_none(getattr(r, "constraint", None)),
                    "constraint_operator": getattr(r, "constraint_operator", None),
                    "threshold": getattr(r, "threshold", None),
                    "operator": getattr(r, "operator", None),
                    "bins": json.dumps(getattr(r, "bins", None) or []),
                    "reference_date": getattr(r, "reference_date", None),
                    "reference_date_col": getattr(r, "reference_date_col", None),
                }

            # Rejection-sampling rules that were never applied this run (no
            # subject sample size ⇒ the destructive fallback was skipped) must
            # not be validated as if they had shaped the data: that would report
            # a misleading PASS/FAIL. Mark SKIPPED so the user sees the rule was
            # not enforced.
            if unenforced_rejection and getattr(rule, "rejection_sampling", False):
                logger.warning(
                    "SKIPPED | %s on '%s' (rejection sampling not applied — no subject sample size set)",
                    rule_name,
                    rule.table_target,
                )
                rows.append(
                    {
                        "type": "rule",
                        "check": rule_name,
                        "rule": rule_name,
                        "table": rule.table_target,
                        "status": "SKIPPED",
                        "failed_rows": 0,
                        "total_rows": 0,
                        "details": (
                            "Rejection sampling not applied (no subject sample size set); "
                            "rule not enforced"
                        ),
                        **_identity(rule),
                    }
                )
                continue

            if rule.table_target not in data_dict:
                logger.warning(f"SKIPPED | {rule_name} (Table '{rule.table_target}' not found)")
                rows.append(
                    {
                        "type": "rule",
                        "check": rule_name,
                        "rule": rule_name,
                        "table": rule.table_target,
                        "status": "SKIPPED",
                        "failed_rows": 0,
                        "total_rows": 0,
                        "details": f"Table '{rule.table_target}' not found in data",
                        **_identity(rule),
                    }
                )
                continue

            view_df = self._get_joined_view(rule, data_dict)
            total = len(view_df)

            # An empty target table validates vacuously (no rows ⇒ no failing
            # rows), which would falsely read as PASS even though the table is
            # broken. Report SKIPPED so the rule never looks "OK" on data that
            # does not exist; the empty table itself is flagged by the
            # column_health general check.
            if total == 0:
                logger.warning(
                    f"SKIPPED | {rule_name} on '{rule.table_target}' (table is empty, 0 rows)"
                )
                rows.append(
                    {
                        "type": "rule",
                        "check": rule_name,
                        "rule": rule_name,
                        "table": rule.table_target,
                        "status": "SKIPPED",
                        "failed_rows": 0,
                        "total_rows": 0,
                        "details": f"Table '{rule.table_target}' is empty (0 rows); rule not validated",
                        **_identity(rule),
                    }
                )
                continue

            # The table has rows, but if every column this rule validates came
            # back entirely empty (all null/blank) there is nothing to check
            # against. Null operands silently satisfy comparisons and match-on-
            # null reconstructions, so such a rule would otherwise read as a
            # vacuous PASS over data that does not exist — exactly what happens
            # to a table that generated blank columns. Report SKIPPED; the empty
            # columns themselves are flagged by the column_health general check.
            validated_cols = [
                col for col in self._rule_validated_columns(rule) if col in view_df.columns
            ]
            if validated_cols and all(_series_all_empty(view_df[col]) for col in validated_cols):
                logger.warning(
                    "SKIPPED | %s on '%s' (validated columns %s are entirely empty)",
                    rule_name,
                    rule.table_target,
                    sorted(validated_cols),
                )
                rows.append(
                    {
                        "type": "rule",
                        "check": rule_name,
                        "rule": rule_name,
                        "table": rule.table_target,
                        "status": "SKIPPED",
                        "failed_rows": 0,
                        "total_rows": total,
                        "details": (
                            f"Columns {sorted(validated_cols)} are empty; rule not validated"
                        ),
                        **_identity(rule),
                    }
                )
                continue

            errors = rule.sanity_check(view_df)
            n_errors = len(errors)

            if n_errors == 0:
                logger.info(f"PASSED | {rule_name} on '{rule.table_target}'")
                rows.append(
                    {
                        "type": "rule",
                        "check": rule_name,
                        "rule": rule_name,
                        "table": rule.table_target,
                        "status": "PASS",
                        "failed_rows": 0,
                        "total_rows": total,
                        "details": "",
                        **_identity(rule),
                    }
                )
            else:
                logger.error(f"FAILED | {rule_name} on '{rule.table_target}' ({n_errors} errors)")
                rows.append(
                    {
                        "type": "rule",
                        "check": rule_name,
                        "rule": rule_name,
                        "table": rule.table_target,
                        "status": "FAIL",
                        "failed_rows": n_errors,
                        "total_rows": total,
                        "details": f"{n_errors}/{total} rows failed",
                        **_identity(rule),
                    }
                )

        if not rows:
            logger.info("No registered rules.")
            return pd.DataFrame()

        report = pd.DataFrame(rows)
        passed = (report["status"] == "PASS").sum()
        total_checks = len(report)
        logger.info(f"\nResult: {passed}/{total_checks} checks passed.")
        return report

    def _rule_validated_columns(self, rule: LogicalRule) -> set[str]:
        """Columns a rule reads/writes when validating, by their final (output) name.

        These are the columns whose values the rule's ``sanity_check`` actually
        inspects. If every one of them that is present in the view is entirely
        empty, the check has nothing to validate against and would pass (or fail)
        vacuously — see ``run_rules_sanity_checks``.
        """
        cols: set[str] = set()
        for attr in ("target_col", "origin_col", "source_col", "aux_col", "canonical_col"):
            value = getattr(rule, attr, None)
            if value:
                cols.add(value)
        part_cols = getattr(rule, "part_cols", None)
        if isinstance(part_cols, dict):
            cols.update(col for col in part_cols.values() if col)
        return cols

    def get_rejection_rules(self) -> list[LogicalRule]:
        """Returns rules flagged for rejection sampling."""
        return [rule for rule in self.rules if rule.rejection_sampling]

    def _build_rejection_view(
        self,
        base_rule: LogicalRule,
        data_dict: dict[str, pd.DataFrame],
        row_id_col: str,
    ) -> pd.DataFrame:
        view_df = self._get_joined_view(
            base_rule,
            data_dict,
            include_target_row_id=True,
            target_row_id_col=row_id_col,
        )

        derived_rules = [
            rule
            for rule in self.rules
            if isinstance(rule, DerivedColumnRule)
            and not rule.rejection_sampling
            and rule.aux_col == base_rule.table_target
        ]
        if not derived_rules:
            return view_df

        for derived_rule in derived_rules:
            try:
                derived_view = self._get_joined_view(
                    derived_rule,
                    data_dict,
                    include_target_row_id=True,
                    target_row_id_col=row_id_col,
                )
            except Exception as exc:
                logger.warning(
                    "Skipping derived rule '%s' for rejection view on '%s': %s",
                    type(derived_rule).__name__,
                    base_rule.table_target,
                    exc,
                )
                continue

            if row_id_col not in derived_view.columns:
                continue

            try:
                derived_series = derived_rule._compute_derived(derived_view)
            except Exception as exc:
                logger.warning(
                    "Failed to compute derived column '%s' for rejection view on '%s': %s",
                    derived_rule.aux_col,
                    base_rule.table_target,
                    exc,
                )
                continue

            derived_map = (
                pd.DataFrame(
                    {
                        row_id_col: derived_view[row_id_col],
                        derived_rule.aux_col: derived_series,
                    }
                )
                .drop_duplicates(row_id_col)
                .set_index(row_id_col)[derived_rule.aux_col]
            )
            view_df[derived_rule.aux_col] = view_df[row_id_col].map(derived_map)

        return view_df

    def collect_rejection_failures(
        self,
        data_dict: dict[str, pd.DataFrame],
        rules: list[LogicalRule] | None = None,
    ) -> dict[str, set[int]]:
        """Collect row indices to reject for the selected rules.

        Returns a mapping of table name to set of row indices to discard.
        """
        rules_to_check = rules if rules is not None else self.get_rejection_rules()
        rejected: dict[str, set[int]] = {}

        for rule in rules_to_check:
            if rule.table_target not in data_dict:
                continue

            target_df = data_dict[rule.table_target]
            row_id_col = "__target_row_id"
            if row_id_col in target_df.columns:
                suffix = 1
                while f"{row_id_col}_{suffix}" in target_df.columns:
                    suffix += 1
                row_id_col = f"{row_id_col}_{suffix}"

            view_df = self._build_rejection_view(rule, data_dict, row_id_col)
            errors = self._demonstrable_violations(rule, view_df)
            if errors.empty or row_id_col not in errors.columns:
                continue

            rejected.setdefault(rule.table_target, set()).update(
                errors[row_id_col].dropna().astype(int).tolist()
            )

        return rejected

    @staticmethod
    def _demonstrable_violations(rule: LogicalRule, view_df: pd.DataFrame) -> pd.DataFrame:
        """Run a rule's sanity check in null-tolerant mode, for rejection sampling.

        Rules that distinguish null operands (Date/Numeric inequality) expose an
        ``allow_null`` flag the *report* uses to flag unverifiable nulls. For
        *rejection* we never want to drop a row we cannot prove violates the rule,
        so force null tolerance for the duration of the check and restore the
        original setting afterwards. Rules without the flag are unaffected.
        """
        if not hasattr(rule, "allow_null"):
            return rule.sanity_check(view_df)
        previous = rule.allow_null
        rule.allow_null = True
        try:
            return rule.sanity_check(view_df)
        finally:
            rule.allow_null = previous


def _series_all_empty(series: pd.Series) -> bool:
    """True when every value in the column is missing: null or blank/whitespace.

    Mirrors the column-health notion of "empty" (true nulls plus blank strings)
    so a column that came back 100% blank is recognised as having no data to
    validate against.
    """
    if len(series) == 0:
        return True
    is_null = series.isna()
    is_blank_str = series.astype(str).str.strip().eq("") & ~is_null
    return bool((is_null | is_blank_str).all())


_UNIT_SECONDS = {
    "years": 365.25 * 86400.0,
    "months": (365.25 / 12.0) * 86400.0,
    "days": 86400.0,
}


@dataclass
class DateToAgeRule(DerivedColumnRule):
    """Derive a span (age / duration) between two dates.

    Convention (matches the UI):
        * ``origin_col`` is the **more recent** date (admission, episode end, ...).
        * ``reference_date`` / ``reference_date_col`` is the **older** date
          (date of birth, episode start, ...).
        * The derived value is ``floor((origin - reference) / unit)``; if
          ``enforce_non_negative`` is True (default), negative spans are
          clipped to 0.

    Default unit is years (classic age-from-DoB use case); set ``unit`` to
    ``"days"`` or ``"months"`` to compute a duration at finer granularity. 

    Arguments:
        reference_date (str, optional): Constant older date to subtract from
            ``origin_col`` (e.g., "2020-01-01"). Required if reference_date_col
            is not provided.
            IMPORTANT: Uses pd.to_datetime, so it must be a date format parseable by pandas.
        reference_date_col (str, optional): Column name to use as the older date
            per row. Required if reference_date is not provided.
        reference_date_table (str, optional): Table that owns ``reference_date_col`` when it
            lives outside ``table_target``. When set, the rule manager joins ``table_target``
            with this table via the existing PK/FK path so the column is available in the
            view passed to :meth:`_compute_derived`. Defaults to ``table_target`` (same table).
        origin_col (str): Column name of the more recent date.
        aux_col (str): Column name where the derived span will be stored. 
        unit (str): One of ``"years"`` (default), ``"months"``, ``"days"``. Controls the
            unit of the derived integer.
        enforce_non_negative (bool): If True (default), values below 0 are
            clipped to 0. Disable to keep the sign when ``origin`` may be older
            than the reference.
        table_origin (str): Set internally to ``reference_date_table`` when cross-table mode
            is in use so the join orchestrator routes correctly. Do not pass directly.
        table_target (str): Name of the target table where the column is created and validated.

    """

    reference_date: str = None
    reference_date_col: str = None
    reference_date_table: str = None
    unit: str = "years"
    enforce_non_negative: bool = True
    table_origin: str = None
    table_target: str = None

    def __post_init__(self) -> None:
        self._require_aux()
        if self.origin_col is None:
            raise ValueError("DateToAgeRule requires 'origin_col'.")
        if self.reference_date is None and self.reference_date_col is None:
            raise ValueError("DateToAgeRule requires 'reference_date' or 'reference_date_col'.")
        if self.reference_date is not None and self.reference_date_col is not None:
            logger.error(
                "DateToAgeRule: specify 'reference_date' or 'reference_date_col', not both."
            )
            logger.info("Defaulting to 'reference_date_col' and ignoring 'reference_date'.")
            self.reference_date = None
        if self.reference_date_table is not None and self.reference_date_col is None:
            raise ValueError(
                "DateToAgeRule: 'reference_date_table' requires "
                "'reference_date_col' to also be set."
            )
        if self.unit not in _UNIT_SECONDS:
            raise ValueError(
                f"DateToAgeRule: unit must be one of {sorted(_UNIT_SECONDS)}, got '{self.unit}'."
            )
        # When the reference column lives in a different table, point
        # ``table_origin`` at it so :meth:`LogicalRuleManager._get_joined_view`
        # joins it with ``table_target`` and ``_compute_derived`` sees both
        # columns in the same dataframe. For DerivedColumnRule subclasses
        # ``table_origin`` is not consulted for column qualification beyond
        # the join orchestrator, so this overload is safe.
        if self.reference_date_table is not None and self.reference_date_table != self.table_target:
            self.table_origin = self.reference_date_table

    def _compute_derived(self, df: pd.DataFrame) -> pd.Series:
        if self.reference_date_col is not None:
            reference_dt = parse_dates(
                df[self.reference_date_col], col_name=self.reference_date_col, utc=True
            )
        else:
            reference_dt = pd.to_datetime(self.reference_date, utc=True)
        origin_dt = parse_dates(df[self.origin_col], col_name=self.origin_col, utc=True)
        seconds_per_unit = _UNIT_SECONDS[self.unit]
        # Convention: origin is the more recent date, reference the older one,
        # so the span is origin - reference. With enforce_non_negative=True we
        # still clip negatives to 0 (kept for backwards compatibility with
        # rules that omit the flag).
        span = (origin_dt - reference_dt).dt.total_seconds() / seconds_per_unit
        span = np.floor(span)
        if self.enforce_non_negative:
            span = span.clip(lower=0)
        return span

    def _reconstruct_origin(self, df: pd.DataFrame) -> pd.Series | None:
        if self.aux_col not in df.columns:
            return None

        if self.reference_date_col is not None:
            reference_dt = parse_dates(
                df[self.reference_date_col], col_name=self.reference_date_col, utc=True
            )
        else:
            reference_dt = pd.to_datetime(self.reference_date, utc=True)

        span = pd.to_numeric(df[self.aux_col], errors="coerce")
        offset_seconds = span * _UNIT_SECONDS[self.unit]
        # span = origin - reference  ⇒  origin = reference + span
        reconstructed = reference_dt + pd.to_timedelta(offset_seconds, unit="s")
        # The output column must stay tz-naive like the rest of the pipeline.
        if isinstance(reconstructed, pd.Series) and reconstructed.dt.tz is not None:
            reconstructed = reconstructed.dt.tz_localize(None)
        return reconstructed

    def sanity_check(self, df: pd.DataFrame) -> pd.DataFrame:
        if self.aux_col not in df.columns or self.origin_col not in df.columns:
            return pd.DataFrame()

        expected = self._compute_derived(df)
        mismatched = df[self.aux_col].fillna(-1) != expected.fillna(-1)
        failing_rows = df[mismatched].copy()
        if not failing_rows.empty:
            failing_rows["error_type"] = "DERIVED_AGE_MISMATCH"
            failing_rows["table_origin"] = self.table_target
            reference_label = (
                self.reference_date_col
                if self.reference_date_col is not None
                else self.reference_date
            )
            failing_rows["details"] = f"{self.aux_col} != age({self.origin_col}, {reference_label})"
        return failing_rows


@dataclass
class DateCompositionRule(LogicalRule):
    """Treat split day/month/year columns as derived from a canonical date.

    Opt-in by design: a dataset may keep ``dob`` plus ``dob_year``/``dob_month``/
    ``dob_day`` for legitimate reasons (e.g. anonymising one but not the
    other). Registering this rule is the user's explicit decision to drop the
    split columns during training and re-derive them deterministically from
    ``canonical_col`` so the output is internally consistent.

    Args:
        canonical_col: Column holding the full date / datetime.
        part_cols: Mapping ``{part_name: column_name}`` where ``part_name`` is
            one of ``year``/``month``/``day``/``hour``/``minute``/``second``.
        table_target: Table where the rule applies.
    """

    canonical_col: str = None
    part_cols: dict[str, str] = field(default_factory=dict)

    _ALLOWED_PARTS = ("year", "month", "day", "hour", "minute", "second")

    def __post_init__(self) -> None:
        if not self.canonical_col:
            raise ValueError("DateCompositionRule requires 'canonical_col'.")
        if not self.part_cols:
            raise ValueError("DateCompositionRule requires non-empty 'part_cols'.")
        invalid = set(self.part_cols) - set(self._ALLOWED_PARTS)
        if invalid:
            raise ValueError(
                f"DateCompositionRule: unknown parts {sorted(invalid)}; "
                f"allowed: {self._ALLOWED_PARTS}."
            )

    def apply_pre(self, df: pd.DataFrame) -> pd.DataFrame:
        cols_to_drop = [c for c in self.part_cols.values() if c in df.columns]
        if not cols_to_drop:
            return df
        return df.drop(columns=cols_to_drop)

    def apply_post(self, df: pd.DataFrame) -> pd.DataFrame:
        if self.canonical_col not in df.columns:
            logger.warning(
                "DateCompositionRule: canonical column '%s' missing in synthetic data; "
                "cannot reconstruct parts %s.",
                self.canonical_col,
                list(self.part_cols.values()),
            )
            return df
        canonical = parse_dates(df[self.canonical_col], col_name=self.canonical_col)
        for part, col in self.part_cols.items():
            df[col] = getattr(canonical.dt, part)
        return df

    def sanity_check(self, df: pd.DataFrame) -> pd.DataFrame:
        if self.canonical_col not in df.columns:
            return pd.DataFrame()
        canonical = parse_dates(df[self.canonical_col], col_name=self.canonical_col)
        mismatches = pd.Series(False, index=df.index)
        for part, col in self.part_cols.items():
            if col not in df.columns:
                continue
            expected = getattr(canonical.dt, part)
            actual = pd.to_numeric(df[col], errors="coerce")
            both_known = expected.notna() & actual.notna()
            mismatches |= (expected != actual) & both_known
        failing = df[mismatches].copy()
        if not failing.empty:
            failing["error_type"] = "DATE_COMPOSITION_MISMATCH"
            failing["table_origin"] = self.table_target
            failing["details"] = (
                f"parts {list(self.part_cols.values())} != decompose({self.canonical_col})"
            )
        return failing


@dataclass
class NumericThresholdRule(DerivedColumnRule):
    """Derive a boolean column based on a numeric threshold.
    Ex. create column is_adult from column age with threshold 18 and operator ">="

    Arguments:
        threshold (float): Numeric threshold for the condition.
        operator (str): Comparison operator, one of ">=", ">", "<=", "<". Default: ">=".
        true_value (Any): Value to assign if condition is True. Default: True.
        false_value (Any): Value to assign if condition is False. Default: False.
        table_origin (str): Name of the reference table for sanity checks.
        table_target (str): Name of the target table where the derived column is created and validated.
    """

    threshold: float = None
    operator: str = ">="
    true_value: Any = True
    false_value: Any = False
    table_origin: str = None
    table_target: str = None

    def __post_init__(self) -> None:
        self._require_aux()
        if self.origin_col is None:
            raise ValueError("NumericThresholdRule requires 'origin_col'.")
        if self.threshold is None:
            raise ValueError("NumericThresholdRule requires 'threshold'.")
        if self.operator not in (">=", ">", "<=", "<"):
            raise ValueError("NumericThresholdRule: operator must be one of '>=', '>', '<=', '<'.")

    def _compute_mask(self, df: pd.DataFrame) -> pd.Series:
        if self.operator == ">=":
            return df[self.origin_col] >= self.threshold
        if self.operator == ">":
            return df[self.origin_col] > self.threshold
        if self.operator == "<=":
            return df[self.origin_col] <= self.threshold
        return df[self.origin_col] < self.threshold

    def _compute_derived(self, df: pd.DataFrame) -> pd.Series:
        return self._compute_mask(df).map({True: self.true_value, False: self.false_value})

    def sanity_check(self, df: pd.DataFrame) -> pd.DataFrame:
        if self.aux_col not in df.columns or self.origin_col not in df.columns:
            logger.warning(
                f"Sanity check for NumericThresholdRule on '{self.table_target}' skipped: "
                f"missing columns '{self.aux_col}' or '{self.origin_col}'."
            )
            logger.debug(f"Available columns: {df.columns.tolist()}.")
            return pd.DataFrame()

        if self.aux_col == self.origin_col:
            mask = self._compute_mask(df)
            failing_rows = df[~mask].copy()
            if not failing_rows.empty:
                failing_rows["error_type"] = "NUMERIC_THRESHOLD_VIOLATION"
                failing_rows["table_origin"] = self.table_target
                failing_rows["details"] = f"{self.aux_col} {self.operator} {self.threshold}"
            return failing_rows

        expected = self._compute_derived(df)
        mismatched = df[self.aux_col].fillna("__missing__") != expected.fillna("__missing__")
        failing_rows = df[mismatched].copy()
        if not failing_rows.empty:
            failing_rows["error_type"] = "DERIVED_THRESHOLD_MISMATCH"
            failing_rows["table_origin"] = self.table_target
            failing_rows["details"] = (
                f"{self.aux_col} != {self.origin_col} {self.operator} {self.threshold}"
            )
        return failing_rows


@dataclass
class NumericBucketRule(DerivedColumnRule):
    """Derive a categorical column by bucketing numeric values.
    Ex. create column age_bucket from column age with bins [0, 18, 65, inf]
        and labels ["child", "adult", "senior"]

    Arguments:
        bins (list[float]): List of bin edges.
        labels (list[str] | None): List of labels for the bins. If None, default labels are used.
            If provided, length must be len(bins) - 1.
        include_lowest (bool): Whether the first bin includes the lowest value.
        right (bool): Whether the bins are right-inclusive.
        table_origin (str): Name of the reference table for sanity checks.
        table_target (str): Name of the target table where the derived column is created and validated.
        drop_origin (bool): Whether to drop the original numeric column after bucketing. Defaults to False.
        reconstruct_origin (bool): Whether to reconstruct the original numeric column during POST if
            it was dropped. Defaults to False. If true, randomly samples within the given bucket range
            for each value. This is a lossy reconstruction
    """

    bins: list[float] = field(default_factory=list)
    labels: list[str] | None = None
    include_lowest: bool = True
    right: bool = False
    table_origin: str = None
    table_target: str = None

    def __post_init__(self) -> None:
        self._require_aux()
        if self.origin_col is None:
            raise ValueError("NumericBucketRule requires 'origin_col'.")
        if not self.bins:
            raise ValueError("NumericBucketRule requires non-empty 'bins'.")
        if self.labels is not None and len(self.labels) != len(self.bins) - 1:
            raise ValueError("NumericBucketRule labels must match bins-1 length.")

    def _compute_derived(self, df: pd.DataFrame) -> pd.Series:
        return pd.cut(
            df[self.origin_col],
            bins=self.bins,
            labels=self.labels,
            include_lowest=self.include_lowest,
            right=self.right,
        )

    def _reconstruct_origin(self, df: pd.DataFrame) -> pd.Series | None:
        if self.aux_col not in df.columns:
            return None

        if self.labels is None:
            intervals = df[self.aux_col]
            lefts = intervals.apply(
                lambda interval: interval.left if pd.notna(interval) else np.nan
            )
            rights = intervals.apply(
                lambda interval: interval.right if pd.notna(interval) else np.nan
            )
        else:
            label_to_bounds: dict[Any, tuple[float, float]] = {
                label: (self.bins[idx], self.bins[idx + 1]) for idx, label in enumerate(self.labels)
            }
            lefts = df[self.aux_col].map(
                lambda label: label_to_bounds.get(label, (np.nan, np.nan))[0]
            )
            rights = df[self.aux_col].map(
                lambda label: label_to_bounds.get(label, (np.nan, np.nan))[1]
            )

        reconstructed: list[float] = []
        for left, right in zip(lefts, rights, strict=False):
            if not np.isfinite(left) or not np.isfinite(right):
                reconstructed.append(np.nan)
                continue

            if self.right:
                lower = np.nextafter(left, right) if not self.include_lowest else left
                upper = right
            else:
                lower = left
                upper = np.nextafter(right, left)

            if lower > upper:
                reconstructed.append(np.nan)
                continue

            reconstructed.append(np.random.uniform(lower, upper))

        return pd.Series(reconstructed, index=df.index)

    def sanity_check(self, df: pd.DataFrame) -> pd.DataFrame:
        if self.aux_col not in df.columns or self.origin_col not in df.columns:
            return pd.DataFrame()

        expected = self._compute_derived(df)
        mismatched = df[self.aux_col].astype(str) != expected.astype(str)
        failing_rows = df[mismatched].copy()
        if not failing_rows.empty:
            failing_rows["error_type"] = "DERIVED_BUCKET_MISMATCH"
            failing_rows["table_origin"] = self.table_target
            failing_rows["details"] = f"{self.aux_col} != bucket({self.origin_col})"
        return failing_rows


@dataclass
class ForeignKeysConsistencyRule(LogicalRule):
    """Reconstructs a redundant FK by copying it from the parent table marked as "context".

    Used when a child table keeps a single context key during training
    and another FK can be derived deterministically from the parent table. Example:
    ``condition.person_id`` can be recovered from ``visit.person_id`` using
    ``condition.visit_occurrence_id`` as context.
    """

    target_col: str = None
    source_col: str = None
    referenced_table: str = None
    table_origin: str = None
    table_target: str = None

    def __post_init__(self) -> None:
        if self.target_col is None:
            raise ValueError("ForeignKeysConsistencyRule requires 'target_col'.")
        if self.source_col is None:
            self.source_col = self.target_col

    def _resolve_parent_source_col(self, df: pd.DataFrame) -> str | None:
        """Resolves the correct source column name in the joined view.

        When LogicalRuleManager._get_joined_view merges child with parent, it uses suffixes=("",
        "_origin") . If both tables share a column name (e.g., both condition and visit have
        person_id), the parent's version becomes person_id_origin to avoid collision.

        So _resolve_parent_source_col first
        checks for {source_col}_origin (the suffixed parent column from the merge), and falls back
        to source_col if no collision occurred.

        Args:
            df (pd.DataFrame): The joined DataFrame to resolve column from.

        Returns:
            str | None: The resolved column name, or None if not found.
        """

        origin_candidate = f"{self.source_col}_origin"
        if origin_candidate in df.columns:
            logger.debug(
                f"Resolved source column for FK consistency: '{origin_candidate}' (due to name collision)"
            )
            return origin_candidate
        if self.source_col in df.columns:
            logger.debug(
                f"Resolved source column for FK consistency: '{self.source_col}' (no name collision)"
            )
            return self.source_col
        logger.warning(
            f"Neither '{self.source_col}' nor '{origin_candidate}' found in DataFrame columns "
            f"for FK consistency rule targeting '{self.target_col}' in '{self.table_target}'."
        )
        return None

    def apply_pre(self, df: pd.DataFrame) -> pd.DataFrame:
        if self.target_col in df.columns:
            logger.debug(
                f"Removing target column '{self.target_col}' for PRE of ForeignKeysConsistencyRule"
            )
            df = df.drop(columns=[self.target_col])
        return df

    def apply_post(self, df: pd.DataFrame) -> pd.DataFrame:
        source_col = self._resolve_parent_source_col(df)
        if source_col is None:
            logger.warning(
                f"Source column for FK consistency rule not found. Skipping POST application for target '{self.target_col}' in '{self.table_target}'."
            )
            return df

        # Don't try to assign back a column from itself representing a self-referencing relationship during POST
        if source_col == self.target_col and self.table_origin == self.table_target:
            logger.debug(
                f"Skipping POST application for self-referencing FK consistency rule on '{self.target_col}' in '{self.table_target}'."
            )
            return df

        logger.debug(
            f"Applying POST for ForeignKeysConsistencyRule: copying from '{source_col}' to '{self.target_col}' in '{self.table_target}'"
        )
        df[self.target_col] = df[source_col]
        return df

    def sanity_check(self, df: pd.DataFrame) -> pd.DataFrame:
        if self.target_col not in df.columns:
            return pd.DataFrame()

        source_col = self._resolve_parent_source_col(df)
        if source_col is None:
            return pd.DataFrame()

        matches = (df[self.target_col] == df[source_col]) | (
            df[self.target_col].isna() & df[source_col].isna()
        )
        failing_rows = df[~matches].copy()

        if not failing_rows.empty:
            failing_rows["error_type"] = "CONTEXT_FK_INCONSISTENCY"
            failing_rows["table_origin"] = self.table_target
            failing_rows["details"] = f"{self.target_col} != {self.table_origin}.{self.source_col}"

        return failing_rows


@dataclass
class DateInequalityRule(LogicalRule):
    """
    Guarantees an order relationship between a date (target) and another date or constant date.
    Transforms the difference into a 'duration' (days) so the model learns it more easily.

    Usage modes:
        - Two columns: origin_col and target_col related by constraint_operator.
        - Constant value: target_col related to constraint by constraint_operator.

    Args:
        origin_col (str, optional): Reference date column (alternative to constraint).
        target_col (str): Target date column (will be removed in PRE).
        aux_col (str, optional): Name for the auxiliary column. Default: auto-generated.
        constraint (str, optional): Constant limit date (alternative to origin_col).
                                    Format: string parseable by pd.to_datetime (e.g.: "2020-01-01").
        constraint_operator (str): Relationship between target and constraint. Values: ">=" (default) or "<=".
                        ">=" -> target >= bound  |  "<=" -> target <= bound
        enforce_non_negative (bool): Whether to enforce non-negative durations. Default: True.
                        If True, negative durations are clipped to 0 during post-processing.
                        If False, durations can be negative (allowing model flexibility).
        allow_null (bool): How the sanity check treats null/unparseable operands.
                        Default False: a null target (or null origin in two-column mode)
                        counts as a violation, because a missing value cannot be shown to
                        satisfy the constraint — this is what stops an entirely-empty column
                        from silently reporting 100% compliance. Set True only when the
                        target column is legitimately nullable and nulls should be ignored.
    """

    origin_col: str = None
    target_col: str = None
    aux_col: str = None
    constraint: str = None
    constraint_operator: str = ">="
    enforce_non_negative: bool = True
    allow_null: bool = False
    table_origin: str = None
    table_target: str = None
    _constraint_dt: pd.Timestamp = field(default=None, init=False, repr=False)
    _flipped: bool = False

    def __post_init__(self):
        if self.origin_col is None and self.constraint is None:
            raise ValueError("DateInequalityRule requires either 'origin_col' or 'constraint'.")
        if self.origin_col is not None and self.constraint is not None:
            raise ValueError("DateInequalityRule: specify 'origin_col' or 'constraint', not both.")
        if self.constraint_operator not in (">=", "<="):
            raise ValueError(
                f"DateInequalityRule: constraint_operator must be '>=' or '<=', got '{self.constraint_operator}'."
            )
        if self.constraint is not None:
            # Normalize to UTC then drop the tz so the bound compares cleanly
            # against the tz-naive columns used throughout PRE/POST/sanity.
            self._constraint_dt = pd.to_datetime(self.constraint, utc=True).tz_localize(None)
        if self.aux_col is None:
            self.aux_col = f"duration_{self.target_col}"

    def _get_bound(self, df: pd.DataFrame):
        """Returns the bound: origin_col column or constant date.

        Args:
            df (pd.DataFrame): DataFrame to get column from.

        Returns:
            pd.Timestamp | pd.Series: The limit date.
        """
        if self._constraint_dt is not None:
            # Rule managers persisted before the naive-UTC convention store an
            # aware timestamp; strip it so old models keep working.
            if self._constraint_dt.tzinfo is not None:
                return self._constraint_dt.tz_localize(None)
            return self._constraint_dt
        return df[self.origin_col]

    def flip(self):
        """Flips the inequality direction and swaps origin and target columns."""
        self.constraint_operator = ">=" if self.constraint_operator == "<=" else "<="
        self.origin_col, self.target_col = self.target_col, self.origin_col
        self.table_origin, self.table_target = self.table_target, self.table_origin
        logger.debug(
            f"Flipped DateInequalityRule: now '{self.target_col}' {self.constraint_operator} '{self.origin_col}'"
        )
        self._flipped = True

    def apply_pre(self, df: pd.DataFrame) -> pd.DataFrame:
        # Normalize to UTC for mixed-offset inputs, then strip the tz: the
        # origin column survives into the engine's training data, and tz-aware
        # values must not leak there (mirrors apply_post).
        df[self.target_col] = parse_dates(
            df[self.target_col], col_name=self.target_col, utc=True
        ).dt.tz_localize(None)
        if self.origin_col is not None:
            df[self.origin_col] = parse_dates(
                df[self.origin_col], col_name=self.origin_col, utc=True
            ).dt.tz_localize(None)
        if self.constraint is not None:
            self._warn_constraint_granularity(df[self.target_col])

        bound = self._get_bound(df)
        # Compute via total seconds and round so datetime inputs with hour-level
        # precision don't get truncated to 0. `.dt.days` would floor a 23h diff
        # to 0; here a sub-day delta rounds to the nearest integer day.
        if self.constraint_operator == ">=":
            delta = (df[self.target_col] - bound).dt.total_seconds() / 86400.0
        else:
            delta = (bound - df[self.target_col]).dt.total_seconds() / 86400.0
        df[self.aux_col] = delta.round().astype("Int64")
        return df.drop(columns=[self.target_col])

    def apply_post(self, df: pd.DataFrame) -> pd.DataFrame:
        if self.origin_col is not None:
            df[self.origin_col] = parse_dates(
                df[self.origin_col],
                col_name=self.origin_col,
                errors="coerce",
                utc=True,
            ).dt.tz_localize(None)

        bound = self._get_bound(df)
        days = pd.to_numeric(df[self.aux_col], errors="coerce")
        if self.enforce_non_negative:
            days = days.clip(lower=0)
        df[self.aux_col] = days
        if self.constraint_operator == ">=":
            reconstructed = bound + pd.to_timedelta(days, unit="D")
        else:
            reconstructed = bound - pd.to_timedelta(days, unit="D")
        if isinstance(reconstructed, pd.Series) and reconstructed.dt.tz is not None:
            reconstructed = reconstructed.dt.tz_localize(None)
        df[self.target_col] = reconstructed
        self._warn_if_reconstruction_degraded(days, reconstructed)
        return df.drop(columns=[self.aux_col])

    def _warn_constraint_granularity(self, target: pd.Series) -> None:
        """Warn when the constraint literal's precision differs from the column's.

        A date-only constraint against a datetime column is interpreted as
        midnight (pandas pads ``00:00:00``); the math stays correct, but the
        user should know which instant the bound actually is. The reverse case
        (time-of-day bound against a date-only column) is flagged too.
        """
        self._pre_warning = None
        constraint_has_time = ":" in str(self.constraint)
        non_null = target.dropna()
        column_has_time = (
            bool((non_null != non_null.dt.normalize()).any()) if len(non_null) else False
        )
        if column_has_time and not constraint_has_time:
            message = (
                f"Constraint '{self.constraint}' has no time component but column "
                f"'{self.target_col}' carries times of day; the bound is interpreted "
                f"as '{self.constraint} 00:00:00'."
            )
        elif constraint_has_time and not column_has_time:
            message = (
                f"Constraint '{self.constraint}' includes a time of day but column "
                f"'{self.target_col}' is date-only."
            )
        else:
            return
        self._pre_warning = {
            "rule": type(self).__name__,
            "table": self.table_target,
            "column": self.target_col,
            "constraint": self.constraint,
            "message": message,
        }
        logger.warning("CONSTRAINT GRANULARITY | %s", message)

    def _warn_if_reconstruction_degraded(self, days: pd.Series, reconstructed) -> None:
        """Flag a target that came out blanker than its inputs justify.

        The rejection-sampling check runs null-tolerant (it cannot prove a null
        violates the rule), so an all-NaT target would otherwise sail through
        with 0 rejections. Record a structured warning the manager surfaces in
        the simulation report. Never imputes — flagging only.
        """
        self._post_warning = None
        if not isinstance(reconstructed, pd.Series) or reconstructed.empty:
            return
        target_null_rate = float(reconstructed.isna().mean())
        days_null_rate = float(days.isna().mean())
        if target_null_rate >= 1.0:
            reason = (
                "all reconstructed values are null"
                if days_null_rate >= 1.0
                else "all reconstructed values are null despite non-null durations"
            )
        elif target_null_rate > days_null_rate:
            reason = "reconstruction introduced nulls beyond the generated durations"
        else:
            return
        self._post_warning = {
            "rule": type(self).__name__,
            "table": self.table_target,
            "column": self.target_col,
            "target_null_rate": target_null_rate,
            "duration_null_rate": days_null_rate,
            "reason": reason,
        }
        logger.error(
            "DEGRADED RECONSTRUCTION | %s on '%s'.'%s': %s "
            "(target null rate %.0f%%, duration null rate %.0f%%).",
            type(self).__name__,
            self.table_target,
            self.target_col,
            reason,
            target_null_rate * 100,
            days_null_rate * 100,
        )

    def sanity_check(self, df: pd.DataFrame) -> pd.DataFrame:
        if self.target_col not in df.columns:
            return pd.DataFrame()

        target_dates = parse_dates(
            df[self.target_col], col_name=self.target_col, errors="coerce", utc=True
        ).dt.tz_localize(None)

        if self._constraint_dt is not None:
            bound_dates = self._get_bound(df)
            bound_label = self.constraint
            bound_null = pd.Series(False, index=df.index)
        else:
            if self.origin_col not in df.columns:
                return pd.DataFrame()
            bound_dates = parse_dates(
                df[self.origin_col], col_name=self.origin_col, errors="coerce", utc=True
            ).dt.tz_localize(None)
            bound_label = self.origin_col
            bound_null = bound_dates.isna()

        if self.constraint_operator == ">=":
            inconsistent_mask = target_dates < bound_dates
            error_expr = f"{self.target_col} < {bound_label}"
        else:
            inconsistent_mask = target_dates > bound_dates
            error_expr = f"{self.target_col} > {bound_label}"

        # NaT comparisons silently evaluate to False, so a null target (or null
        # origin in two-column mode) would otherwise be counted as compliant —
        # that is exactly how an entirely-empty column reported 100% compliance.
        # Treat unverifiable null operands as violations unless the rule opts in
        # to nullable values.
        inconsistent_mask = pd.Series(inconsistent_mask, index=df.index).fillna(False)
        null_mask = target_dates.isna() | bound_null
        violation_mask = inconsistent_mask if self.allow_null else (inconsistent_mask | null_mask)

        failing_rows = df[violation_mask].copy()
        if not failing_rows.empty:
            failing_rows["error_type"] = "TEMPORAL_INCONSISTENCY"
            failing_rows["table_origin"] = self.table_target
            details = (
                error_expr
                + " | "
                + self.target_col
                + "="
                + failing_rows[self.target_col].astype(str)
            )
            null_failures = null_mask[violation_mask]
            failing_rows["details"] = details.mask(
                null_failures.to_numpy(), f"null operand, cannot verify: {error_expr}"
            )
        return failing_rows


@dataclass
class NumericInequalityRule(LogicalRule):
    """
    Guarantees that a numeric column is >= another numeric column or >= a constant value.
    Transforms the difference into an auxiliary column so the model can learn it.

    Numeric inequality rule.

    Usage modes:
        - Two columns: origin_col and target_col related by constraint_operator.
        - Constant value: target_col related to constraint by constraint_operator.

    Args:
        origin_col (str, optional): Reference numeric column (alternative to constraint).
        target_col (str): Target numeric column (will be removed in PRE).
        aux_col (str, optional): Name for the auxiliary column. Default: auto-generated.
        constraint (float, optional): Constant value as bound (alternative to origin_col).
        constraint_operator (str): Relationship between target and bound. Values: ">=" (default) or "<=".
                        ">=" → target >= bound  |  "<=" → target <= bound
        allow_null (bool): How the sanity check treats null/unparseable operands.
                        Default False: a null target (or null origin in two-column mode)
                        counts as a violation, since a missing value cannot be shown to
                        satisfy the constraint. Set True only when the target column is
                        legitimately nullable and nulls should be ignored.
    """

    origin_col: str = None
    target_col: str = None
    aux_col: str = None
    constraint: float = None
    constraint_operator: str = ">="
    allow_null: bool = False
    table_origin: str = None
    table_target: str = None
    _flipped: bool = False

    def __post_init__(self):
        if self.origin_col is None and self.constraint is None:
            raise ValueError("NumericInequalityRule requires either 'origin_col' or 'constraint'.")
        if self.origin_col is not None and self.constraint is not None:
            raise ValueError(
                "NumericInequalityRule: specify 'origin_col' or 'constraint', not both."
            )
        if self.constraint_operator not in (">=", "<="):
            raise ValueError(
                f"NumericInequalityRule: constraint_operator must be '>=' or '<=', got '{self.constraint_operator}'."
            )
        if self.aux_col is None:
            self.aux_col = f"diff_{self.target_col}"

    def _get_bound(self, df: pd.DataFrame):
        """Returns the bound: origin_col column or scalar value.

        Args:
            df (pd.DataFrame): DataFrame to get column from.

        Returns:
            float | pd.Series: The limit value.
        """
        if self.constraint is not None:
            return self.constraint
        return df[self.origin_col]

    def flip(self):
        """Flips the inequality direction and swaps origin and target columns."""
        self.constraint_operator = ">=" if self.constraint_operator == "<=" else "<="
        self.origin_col, self.target_col = self.target_col, self.origin_col
        self.table_origin, self.table_target = self.table_target, self.table_origin
        logger.debug(
            f"Flipped NumericInequalityRule: now '{self.target_col}' {self.constraint_operator} '{self.origin_col}'"
        )
        self._flipped = True

    def apply_pre(self, df: pd.DataFrame) -> pd.DataFrame:
        bound = self._get_bound(df)
        if self.constraint_operator == ">=":
            df[self.aux_col] = df[self.target_col] - bound
        else:
            df[self.aux_col] = bound - df[self.target_col]
        return df.drop(columns=[self.target_col])

    def apply_post(self, df: pd.DataFrame) -> pd.DataFrame:
        bound = self._get_bound(df)
        df[self.aux_col] = df[self.aux_col].clip(lower=0)
        if self.constraint_operator == ">=":
            df[self.target_col] = bound + df[self.aux_col]
        else:
            df[self.target_col] = bound - df[self.aux_col]
        return df.drop(columns=[self.aux_col])

    def sanity_check(self, df: pd.DataFrame) -> pd.DataFrame:
        if self.target_col not in df.columns:
            return pd.DataFrame()

        bound_label = str(self.constraint) if self.constraint is not None else self.origin_col
        target_vals = pd.to_numeric(df[self.target_col], errors="coerce")

        if self.constraint is not None:
            bound_vals = self.constraint
            bound_null = pd.Series(False, index=df.index)
        else:
            if self.origin_col not in df.columns:
                return pd.DataFrame()
            bound_vals = pd.to_numeric(df[self.origin_col], errors="coerce")
            bound_null = bound_vals.isna()

        if self.constraint_operator == ">=":
            inconsistent_mask = target_vals < bound_vals
            error_expr = f"{self.target_col} < {bound_label}"
        else:
            inconsistent_mask = target_vals > bound_vals
            error_expr = f"{self.target_col} > {bound_label}"

        # NaN comparisons silently evaluate to False, so a null/unparseable target
        # (or null origin in two-column mode) would otherwise be counted as
        # compliant. Treat unverifiable null operands as violations unless the
        # rule opts in to nullable values.
        inconsistent_mask = pd.Series(inconsistent_mask, index=df.index).fillna(False)
        null_mask = target_vals.isna() | bound_null
        violation_mask = inconsistent_mask if self.allow_null else (inconsistent_mask | null_mask)

        failing_rows = df[violation_mask].copy()
        if not failing_rows.empty:
            failing_rows["error_type"] = "NUMERIC_INEQUALITY_VIOLATION"
            failing_rows["table_origin"] = self.table_target
            details = (
                error_expr
                + " | "
                + self.target_col
                + "="
                + failing_rows[self.target_col].astype(str)
            )
            null_failures = null_mask[violation_mask]
            failing_rows["details"] = details.mask(
                null_failures.to_numpy(), f"null operand, cannot verify: {error_expr}"
            )
        return failing_rows


@dataclass
class SemanticConsistencyRule(LogicalRule, ABC):
    """
    Base class for semantic consistency in conditioned categorical variables.
    Converts categories into continuous [0,1] intervals within specific groups.

    Args:
        origin_col (str): Grouping column (used when no composite keys are set).
        target_col (str): Categorical column to transform.
        aux_col (str, optional): Numeric auxiliary column.
    """

    origin_col: str = None
    target_col: str = None
    aux_col: str = None
    table_origin: str = None
    table_target: str = None
    group_cols: list[str] = field(default_factory=list)
    _mappings: dict[Any, list[tuple[float, Any]]] = field(default_factory=dict, init=False)
    _valid_combinations: dict[Any, set[Any]] = field(default_factory=dict, init=False)

    def __post_init__(self):
        aux_suffix = "score"
        if self.aux_col is None:
            self.aux_col = f"{self.target_col}_{aux_suffix}"

    def add_group_key(self, key_col: str) -> None:
        if not key_col:
            raise ValueError("SemanticConsistencyRule add_group_key requires 'key_col'.")
        if not self.group_cols and self.origin_col:
            self.group_cols = [self.origin_col]
        if key_col not in self.group_cols:
            self.group_cols.append(key_col)

    def _get_group_cols(self) -> list[str]:
        if self.group_cols:
            return list(self.group_cols)
        if self.origin_col:
            return [self.origin_col]
        return []

    def _group_key_series(self, df: pd.DataFrame) -> pd.Series:
        group_cols = self._get_group_cols()
        if not group_cols:
            raise ValueError("SemanticConsistencyRule requires at least one group column.")
        if len(group_cols) == 1:
            return df[group_cols[0]]
        return pd.Series(
            list(zip(*(df[col] for col in group_cols))),
            index=df.index,
        )

    def _group_label(self) -> str:
        group_cols = self._get_group_cols()
        return "|".join(group_cols) if len(group_cols) > 1 else group_cols[0]

    @abstractmethod
    def _calculate_intervals(self, subset: pd.Series) -> list[tuple[float, Any]]:
        """
        Defines how intervals are distributed in the [0,1] range for a group.

        Args:
            subset (pd.Series): Series with categorical values of the current group.

        Returns:
            List[Tuple[float, Any]]: List of tuples (upper_limit, category_name).
        """
        pass

    def _generate_valid_combinations(self, df: pd.DataFrame) -> None:
        """Generates the valid (origin_col, target_col) combinations from the original data.

        This is used for sanity checks to ensure that no invalid category is assigned to a group.
        Normally generated in PRE, we extracted it so that we can use it for rejection sampling.
        Args:
            df (pd.DataFrame): The original DataFrame to extract valid combinations from.
        """
        group_keys = self._group_key_series(df)
        df["_group_key"] = group_keys
        unique_groups = df["_group_key"].dropna().unique()
        for group in unique_groups:
            subset = df[df["_group_key"] == group]
            if subset.empty:
                continue
            present_categories = set(subset[self.target_col].dropna().unique())
            self._valid_combinations[group] = present_categories

    def apply_pre(self, df: pd.DataFrame) -> pd.DataFrame:
        df["_group_key"] = self._group_key_series(df)
        unique_groups = df["_group_key"].dropna().unique()

        # Temporary columns for vectorization
        df["_temp_lower"] = 0.0
        df["_temp_upper"] = 0.0

        for group in unique_groups:
            mask = df["_group_key"] == group
            subset = df[mask]

            if subset.empty:
                continue

            # Register valid combinations for sanity check
            present_categories = set(subset[self.target_col].dropna().unique())
            self._valid_combinations[group] = present_categories

            # Delegate interval calculation to concrete implementation
            group_intervals = self._calculate_intervals(subset[self.target_col])
            self._mappings[group] = group_intervals

            # Fast mapping category -> limits
            category_to_limits = {}
            prev_limit = 0.0
            for upper, category in group_intervals:
                category_to_limits[category] = (prev_limit, upper)
                prev_limit = upper
            for category, (lower, upper) in category_to_limits.items():
                cat_mask = mask & (df[self.target_col] == category)
                df.loc[cat_mask, "_temp_lower"] = lower
                df.loc[cat_mask, "_temp_upper"] = upper

        # Jittering: Generamos valor continuo dentro del intervalo asignado
        df[self.aux_col] = np.random.uniform(df["_temp_lower"], df["_temp_upper"])

        return df.drop(columns=[self.target_col, "_temp_lower", "_temp_upper", "_group_key"])

    def apply_post(self, df: pd.DataFrame) -> pd.DataFrame:
        df["_group_key"] = self._group_key_series(df)

        def get_category(row):
            group = row["_group_key"]
            aux_value = row[self.aux_col]

            if pd.isna(group) or pd.isna(aux_value):
                return None
            if group not in self._mappings:
                return None

            intervals = self._mappings[group]
            breakpoints = [i[0] for i in intervals]

            # Efficient binary search to find which interval the score falls into
            idx = bisect.bisect_left(breakpoints, aux_value)
            if idx >= len(intervals):
                idx = len(intervals) - 1

            return intervals[idx][1]

        df[self.target_col] = df.apply(get_category, axis=1)
        return df.drop(columns=[self.aux_col, "_group_key"])

    def sanity_check(self, df: pd.DataFrame) -> pd.DataFrame:
        """
        Verifies that there are no (origin_col, target_col) combinations
        that were not present in the original data.
        """
        group_cols = self._get_group_cols()
        if not group_cols or self.target_col not in df.columns:
            logger.warning(
                f"Sanity check for SemanticConsistencyRule on '{self.table_target}' skipped: "
                f"missing group columns {group_cols} or target column '{self.target_col}'."
            )
            return pd.DataFrame()
        if any(col not in df.columns for col in group_cols):
            logger.warning(
                f"Sanity check for SemanticConsistencyRule on '{self.table_target}' skipped: "
                f"missing group columns {group_cols} or target column '{self.target_col}'."
            )
            return pd.DataFrame()

        # If apply_pre was not executed or there are no saved rules, we cannot validate
        if not self._valid_combinations:
            return pd.DataFrame()

        group_keys = self._group_key_series(df)
        error_mask = pd.Series(False, index=df.index)

        # Iterate over KNOWN groups to verify their rules
        # Groups that were never seen in PRE are ignored (we don't have a rule for them)
        for group, allowed_cats in self._valid_combinations.items():
            # Filter rows that belong to the current group
            # Note: Handle NaN in origin_col if necessary
            group_mask = group_keys == group

            if not group_mask.any():
                continue

            # Check if there is any category NOT allowed for this group
            # We use ~isin(allowed_cats)
            # Note: If target_col is NaN, isin returns False, so ~False=True (error).
            #       If we allow NaN in target, it should be in allowed_cats.
            current_errors = group_mask & (~df[self.target_col].isin(allowed_cats))
            error_mask |= current_errors

        failing_rows = df[error_mask].copy()

        if not failing_rows.empty:
            group_label = self._group_label()
            group_values = group_keys.loc[failing_rows.index].astype(str)
            failing_rows["error_type"] = "SEMANTIC_INCONSISTENCY"
            failing_rows["table_origin"] = self.table_target
            failing_rows["details"] = (
                f"Group '{group_label}'="
                + group_values
                + f" has invalid category '{self.target_col}'="
                + failing_rows[self.target_col].astype(str)
            )

        return failing_rows


@dataclass
class SemanticProportionalConsistencyRule(SemanticConsistencyRule):
    """
    PROPORTIONAL Semantic Strategy: interval size equals real frequency.
    Forces synthetic data to preserve the original statistical distribution.

    Example:
        If 'Flu' appears 80% of the time, its interval size will be 0.8.
    """

    def _calculate_intervals(self, subset: pd.Series) -> list[tuple[float, Any]]:
        counts = subset.value_counts(normalize=True).sort_index()
        cumulative = 0.0
        intervals = []

        for category, freq in counts.items():
            upper = cumulative + freq
            intervals.append((upper, category))
            cumulative = upper

        if intervals:
            intervals[-1] = (1.0, intervals[-1][1])  # Floating point correction
        return intervals


@dataclass
class SemanticRankingConsistencyRule(SemanticConsistencyRule):
    """
    RANKING Semantic Strategy: all intervals have the same size (equidistant).
    Allows the model to adjust proportions (learning which score ranges it prefers),
    but guarantees that only semantically valid combinations are generated.

    Example:
        If there are 4 diseases, each has an interval of 0.25, ordered by frequency.
    """

    def _calculate_intervals(self, subset: pd.Series) -> list[tuple[float, Any]]:
        # Sort by frequency to group common categories in low scores
        unique_categories = subset.value_counts().index.tolist()
        n = len(unique_categories)

        if n == 0:
            return []

        step = 1.0 / n
        cumulative = 0.0
        intervals = []

        for category in unique_categories:
            upper = cumulative + step
            intervals.append((upper, category))
            cumulative = upper

        if intervals:
            intervals[-1] = (1.0, intervals[-1][1])
        return intervals
